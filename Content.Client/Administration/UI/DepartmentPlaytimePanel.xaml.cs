using System.Linq;
using Content.Shared.Roles;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.Administration.UI;

[GenerateTypedNameReferences]
public sealed partial class DepartmentPlaytimePanel : PanelContainer
{
    private static readonly Color Grey = Color.FromHex("#ccc");

    public Action? OnSelectionChanged;

    private readonly string _name;
    private readonly List<(JobPrototype Job, CheckBox Button)> _jobs = new();

    public DepartmentPlaytimePanel(string name, Color color, IEnumerable<JobPrototype> jobs, Func<JobPrototype, string?> tooltip)
    {
        RobustXamlLoader.Load(this);

        _name = name;
        Department.Text = name;
        Department.Modulate = color;
        Department.OnPressed += _ =>
        {
            foreach (var (_, button) in _jobs)
            {
                if (button.Visible)
                    button.Pressed = Department.Pressed;
            }

            UpdateHeader();
            OnSelectionChanged?.Invoke();
        };

        foreach (var job in jobs)
        {
            var button = new CheckBox { Text = job.LocalizedName, ToolTip = tooltip(job) };
            if (string.IsNullOrEmpty(job.PlayTimeTracker.Id))
                button.Modulate = Grey;

            button.OnPressed += _ =>
            {
                UpdateHeader();
                OnSelectionChanged?.Invoke();
            };
            JobsContainer.AddChild(button);
            _jobs.Add((job, button));
        }
    }

    public IEnumerable<JobPrototype> SelectedJobs()
    {
        return _jobs
            .Where(entry => entry.Button.Pressed)
            .Select(entry => entry.Job);
    }

    public void SelectShown()
    {
        foreach (var (_, button) in _jobs)
        {
            if (button.Visible)
                button.Pressed = true;
        }

        UpdateHeader();
    }

    public void ClearSelection()
    {
        foreach (var (_, button) in _jobs)
        {
            button.Pressed = false;
        }

        UpdateHeader();
    }

    public void UpdateState(Dictionary<string, TimeSpan>? trackers)
    {
        foreach (var (job, button) in _jobs)
        {
            button.Text = trackers == null || string.IsNullOrEmpty(job.PlayTimeTracker.Id)
                ? job.LocalizedName
                : Loc.GetString("playtime-window-job",
                    ("job", job.LocalizedName),
                    ("time", PlaytimeWindow.FormatTime(trackers.GetValueOrDefault(job.PlayTimeTracker.Id))));
            button.Disabled = trackers == null;
        }

        Department.Disabled = trackers == null;
    }

    public void ApplyFilter(string search)
    {
        var departmentMatches = search.Length == 0 || _name.Contains(search, StringComparison.OrdinalIgnoreCase);

        foreach (var (job, button) in _jobs)
        {
            button.Visible = departmentMatches ||
                             job.LocalizedName.Contains(search, StringComparison.OrdinalIgnoreCase) ||
                             job.ID.Contains(search, StringComparison.OrdinalIgnoreCase);
        }

        Visible = _jobs.Any(entry => entry.Button.Visible);
        UpdateHeader();
    }

    private void UpdateHeader()
    {
        var shown = _jobs.Where(entry => entry.Button.Visible).ToList();
        var selected = shown.Count(entry => entry.Button.Pressed);

        Department.Pressed = shown.Count > 0 && selected == shown.Count;
        Count.Text = $"{selected} / {shown.Count}";
    }
}
