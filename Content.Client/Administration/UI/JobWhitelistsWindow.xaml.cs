using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared.Administration;
using Content.Shared.Roles;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client.Administration.UI;

/// <summary>
/// This should generally be preferred to a blanket whitelist (Whitelisted: True) since
/// being good with a batong doesn't mean you know engineering and vice versa.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class JobWhitelistsWindow : FancyWindow
{
    [Dependency] private readonly IPrototypeManager _proto = default!;

    public Action<List<ProtoId<JobPrototype>>, bool>? OnSetJobs;
    public Action<bool>? OnSetServerWhitelisted;

    private readonly List<DepartmentWhitelistPanel> _panels = new();
    private HashSet<ProtoId<JobPrototype>> _whitelists = new();

    public JobWhitelistsWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        PlayerName.Text = "???";
        Summary.Text = Loc.GetString("job-whitelists-window-loading");

        BuildPanels();

        ServerWhitelist.OnPressed += _ => OnSetServerWhitelisted?.Invoke(ServerWhitelist.Pressed);
        Search.OnTextChanged += _ => ApplyFilter();
        OnlyRequired.OnPressed += _ => ApplyFilter();
        GrantShown.OnPressed += _ => SetShown(true);
        RevokeShown.OnPressed += _ => SetShown(false);

        ApplyFilter();
    }

    public void HandleState(JobWhitelistsEuiState state)
    {
        PlayerName.Text = state.PlayerName;
        _whitelists = state.Whitelists;

        var loaded = state.ServerWhitelisted != null;
        ServerWhitelist.Disabled = !loaded;
        ServerWhitelist.Pressed = state.ServerWhitelisted ?? false;
        GrantShown.Disabled = !loaded;
        RevokeShown.Disabled = !loaded;

        foreach (var panel in _panels)
        {
            panel.UpdateState(_whitelists, loaded);
        }

        if (!loaded)
            return;

        var required = _proto.EnumeratePrototypes<JobPrototype>().Where(job => job.Whitelisted).ToList();
        Summary.Text = Loc.GetString("job-whitelists-window-summary",
            ("whitelisted", required.Count(job => _whitelists.Contains(job.ID))),
            ("total", required.Count));
    }

    private void BuildPanels()
    {
        var departments = _proto.EnumeratePrototypes<DepartmentPrototype>()
            .OrderBy(department => department, DepartmentUIComparer.Instance)
            .ToList();

        foreach (var department in departments)
        {
            var jobs = department.Roles
                .Select(id => _proto.TryIndex(id, out var job) ? job : null)
                .OfType<JobPrototype>();

            AddPanel(new DepartmentWhitelistPanel(Loc.GetString($"department-{department.ID}"), department.Color, jobs));
        }

        var inDepartment = departments.SelectMany(department => department.Roles).ToHashSet();
        var others = _proto.EnumeratePrototypes<JobPrototype>()
            .Where(job => !inDepartment.Contains(job.ID))
            .OrderBy(job => job.LocalizedName);

        AddPanel(new DepartmentWhitelistPanel(Loc.GetString("job-whitelists-window-other"), Color.White, others));
    }

    private void AddPanel(DepartmentWhitelistPanel panel)
    {
        panel.OnSetJobs += (jobs, whitelisting) => OnSetJobs?.Invoke(jobs, whitelisting);
        panel.UpdateState(_whitelists, false);
        _panels.Add(panel);
        Departments.AddChild(panel);
    }

    private void ApplyFilter()
    {
        var search = Search.Text.Trim();
        foreach (var panel in _panels)
        {
            panel.ApplyFilter(search, OnlyRequired.Pressed);
        }
    }

    private void SetShown(bool whitelisting)
    {
        var jobs = _panels
            .SelectMany(panel => panel.ShownJobs())
            .Where(id => _whitelists.Contains(id) != whitelisting)
            .Distinct()
            .ToList();

        if (jobs.Count > 0)
            OnSetJobs?.Invoke(jobs, whitelisting);
    }
}
