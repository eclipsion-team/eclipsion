using System.Linq;
using Content.Shared.Roles;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client.Administration.UI;

[GenerateTypedNameReferences]
public sealed partial class DepartmentWhitelistPanel : PanelContainer
{
    private static readonly Color Grey = Color.FromHex("#ccc");

    public Action<List<ProtoId<JobPrototype>>, bool>? OnSetJobs;

    private readonly string _name;
    private readonly List<(JobPrototype Job, CheckBox Button)> _jobs = new();
    private HashSet<ProtoId<JobPrototype>> _whitelists = new();

    public DepartmentWhitelistPanel(string name, Color color, IEnumerable<JobPrototype> jobs)
    {
        RobustXamlLoader.Load(this);

        _name = name;
        Department.Text = name;
        Department.Modulate = color;
        Department.OnPressed += _ =>
        {
            // only request the jobs that actually change
            var changed = ShownJobs()
                .Where(id => _whitelists.Contains(id) != Department.Pressed)
                .ToList();

            if (changed.Count > 0)
                OnSetJobs?.Invoke(changed, Department.Pressed);
        };

        foreach (var job in jobs)
        {
            var button = new CheckBox { Text = job.LocalizedName };
            if (!job.Whitelisted)
            {
                button.Modulate = Grey;
                button.ToolTip = Loc.GetString("job-whitelists-window-not-required");
            }
            else if (job.WhitelistGroup != null)
            {
                button.ToolTip = Loc.GetString("job-whitelists-window-group", ("group", job.WhitelistGroup));
            }

            var id = new ProtoId<JobPrototype>(job.ID);
            button.OnPressed += _ => OnSetJobs?.Invoke(new List<ProtoId<JobPrototype>> { id }, button.Pressed);
            JobsContainer.AddChild(button);
            _jobs.Add((job, button));
        }
    }

    public IEnumerable<ProtoId<JobPrototype>> ShownJobs()
    {
        return _jobs
            .Where(entry => entry.Button.Visible)
            .Select(entry => new ProtoId<JobPrototype>(entry.Job.ID));
    }

    public void UpdateState(HashSet<ProtoId<JobPrototype>> whitelists, bool loaded)
    {
        _whitelists = whitelists;
        foreach (var (job, button) in _jobs)
        {
            button.Pressed = whitelists.Contains(job.ID);
            button.Disabled = !loaded;
        }

        Department.Disabled = !loaded;
        UpdateHeader();
    }

    public void ApplyFilter(string search, bool onlyRequired)
    {
        var departmentMatches = search.Length == 0 || _name.Contains(search, StringComparison.OrdinalIgnoreCase);

        foreach (var (job, button) in _jobs)
        {
            button.Visible = (!onlyRequired || job.Whitelisted) &&
                             (departmentMatches ||
                              job.LocalizedName.Contains(search, StringComparison.OrdinalIgnoreCase) ||
                              job.ID.Contains(search, StringComparison.OrdinalIgnoreCase));
        }

        Visible = _jobs.Any(entry => entry.Button.Visible);
        UpdateHeader();
    }

    private void UpdateHeader()
    {
        var shown = ShownJobs().ToList();
        var whitelisted = shown.Count(id => _whitelists.Contains(id));

        Department.Pressed = shown.Count > 0 && whitelisted == shown.Count;
        Count.Text = $"{whitelisted} / {shown.Count}";
    }
}
