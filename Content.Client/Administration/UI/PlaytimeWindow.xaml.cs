using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared.Administration;
using Content.Shared.Customization.Systems;
using Content.Shared.Players.PlayTimeTracking;
using Content.Shared.Roles;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client.Administration.UI;

[GenerateTypedNameReferences]
public sealed partial class PlaytimeWindow : FancyWindow
{
    [Dependency] private readonly IPrototypeManager _proto = default!;

    public Action<string>? OnSelectPlayer;
    public Action<List<ProtoId<PlayTimeTrackerPrototype>>, TimeSpan, bool>? OnChange;
    public Action<List<ProtoId<JobPrototype>>>? OnMeetRequirements;

    private readonly List<DepartmentPlaytimePanel> _panels = new();
    private Dictionary<string, TimeSpan>? _trackers;

    public PlaytimeWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        BuildPanels();

        PlayerList.OnSelectionChanged += info =>
        {
            if (info != null)
                OnSelectPlayer?.Invoke(info.SessionId.ToString());
        };
        FindPlayer.OnTextEntered += _ => Find();
        FindButton.OnPressed += _ => Find();

        Overall.OnPressed += _ => UpdateButtons();
        TimeInput.OnTextChanged += _ => UpdateButtons();
        AddButton.OnPressed += _ => Change(false);
        SetButton.OnPressed += _ => Change(true);
        MeetButton.OnPressed += _ => MeetRequirements();

        Search.OnTextChanged += _ => ApplyFilter();
        SelectShown.OnPressed += _ =>
        {
            foreach (var panel in _panels)
            {
                panel.SelectShown();
            }

            UpdateButtons();
        };
        ClearSelection.OnPressed += _ =>
        {
            Overall.Pressed = false;
            foreach (var panel in _panels)
            {
                panel.ClearSelection();
            }

            UpdateButtons();
        };

        ApplyFilter();
        HandleState(new PlaytimeEuiState(null, false, null, null));
    }

    public void HandleState(PlaytimeEuiState state)
    {
        _trackers = state.Trackers;

        PlayerName.Text = state.PlayerName ?? Loc.GetString("playtime-window-no-player");
        Summary.Text = state.PlayerName == null
            ? null
            : Loc.GetString(state.Trackers == null
                ? "playtime-window-loading"
                : state.Online ? "playtime-window-online" : "playtime-window-offline");

        Status.Text = state.Status;
        Status.Visible = state.Status != null;

        var overall = Loc.GetString("playtime-window-overall");
        Overall.Text = _trackers == null
            ? overall
            : Loc.GetString("playtime-window-job",
                ("job", overall),
                ("time", FormatTime(_trackers.GetValueOrDefault(PlayTimeTrackingShared.TrackerOverall.Id))));
        Overall.Disabled = _trackers == null;

        foreach (var panel in _panels)
        {
            panel.UpdateState(_trackers);
        }

        UpdateButtons();
    }

    public static string FormatTime(TimeSpan time)
    {
        var sign = time < TimeSpan.Zero ? "-" : "";
        time = time.Duration();

        return sign + Loc.GetString("playtime-window-time", ("hours", (int) time.TotalHours), ("minutes", time.Minutes));
    }

    private void BuildPanels()
    {
        var jobsByTracker = _proto.EnumeratePrototypes<JobPrototype>()
            .Where(job => !string.IsNullOrEmpty(job.PlayTimeTracker.Id))
            .GroupBy(job => job.PlayTimeTracker.Id)
            .ToDictionary(group => group.Key, group => group.ToList());

        var departments = _proto.EnumeratePrototypes<DepartmentPrototype>()
            .OrderBy(department => department, DepartmentUIComparer.Instance)
            .ToList();

        foreach (var department in departments)
        {
            var jobs = department.Roles
                .Select(id => _proto.TryIndex(id, out var job) ? job : null)
                .OfType<JobPrototype>();

            AddPanel(new DepartmentPlaytimePanel(Loc.GetString($"department-{department.ID}"),
                department.Color,
                jobs,
                job => Tooltip(job, jobsByTracker)));
        }

        var inDepartment = departments.SelectMany(department => department.Roles).ToHashSet();
        var others = _proto.EnumeratePrototypes<JobPrototype>()
            .Where(job => !inDepartment.Contains(job.ID))
            .OrderBy(job => job.LocalizedName);

        AddPanel(new DepartmentPlaytimePanel(Loc.GetString("playtime-window-other"),
            Color.White,
            others,
            job => Tooltip(job, jobsByTracker)));
    }

    private void AddPanel(DepartmentPlaytimePanel panel)
    {
        panel.OnSelectionChanged += UpdateButtons;
        _panels.Add(panel);
        Departments.AddChild(panel);
    }

    private string? Tooltip(JobPrototype job, Dictionary<string, List<JobPrototype>> jobsByTracker)
    {
        var lines = new List<string>();

        if (!jobsByTracker.TryGetValue(job.PlayTimeTracker.Id, out var sharing))
        {
            lines.Add(Loc.GetString("playtime-window-no-tracker"));
        }
        else if (sharing.Count > 1)
        {
            lines.Add(Loc.GetString("playtime-window-shared",
                ("jobs", string.Join(", ", sharing.Where(other => other != job).Select(other => other.LocalizedName)))));
        }

        var requirements = new List<string>();
        foreach (var requirement in job.Requirements ?? new List<CharacterRequirement>())
        {
            if (requirement.Inverted)
                continue;

            switch (requirement)
            {
                case CharacterPlaytimeRequirement { Min: var min } playtime when min > TimeSpan.Zero:
                    var name = jobsByTracker.TryGetValue(playtime.Tracker.Id, out var users)
                        ? users[0].LocalizedName
                        : playtime.Tracker.Id;
                    requirements.Add(Loc.GetString("playtime-window-requirement-tracker",
                        ("time", FormatTime(min)),
                        ("job", name)));
                    break;
                case CharacterOverallTimeRequirement { Min: var min } when min > TimeSpan.Zero:
                    requirements.Add(Loc.GetString("playtime-window-requirement-overall", ("time", FormatTime(min))));
                    break;
                case CharacterDepartmentTimeRequirement { Min: var min } department when min > TimeSpan.Zero:
                    requirements.Add(Loc.GetString("playtime-window-requirement-department",
                        ("time", FormatTime(min)),
                        ("department", Loc.GetString($"department-{department.Department.Id}"))));
                    break;
            }
        }

        if (requirements.Count > 0)
            lines.Add(Loc.GetString("playtime-window-requirements", ("requirements", string.Join(", ", requirements))));

        return lines.Count > 0 ? string.Join("\n", lines) : null;
    }

    private void Find()
    {
        var player = FindPlayer.Text.Trim();
        if (player.Length > 0)
            OnSelectPlayer?.Invoke(player);
    }

    private void ApplyFilter()
    {
        var search = Search.Text.Trim();
        foreach (var panel in _panels)
        {
            panel.ApplyFilter(search);
        }
    }

    private List<JobPrototype> SelectedJobs()
    {
        return _panels
            .SelectMany(panel => panel.SelectedJobs())
            .DistinctBy(job => job.ID)
            .ToList();
    }

    private List<ProtoId<PlayTimeTrackerPrototype>> SelectedTrackers()
    {
        var trackers = SelectedJobs()
            .Select(job => job.PlayTimeTracker)
            .Where(tracker => !string.IsNullOrEmpty(tracker.Id))
            .ToList();

        if (Overall.Pressed)
            trackers.Add(PlayTimeTrackingShared.TrackerOverall);

        return trackers.Distinct().ToList();
    }

    private void UpdateButtons()
    {
        var loaded = _trackers != null;
        var valid = PlayTimeTrackingShared.TryParseTime(TimeInput.Text, out var time);
        var jobs = SelectedJobs();
        var trackers = SelectedTrackers();

        TimePreview.Text = TimeInput.Text.Trim().Length == 0
            ? null
            : valid ? FormatTime(time) : Loc.GetString("playtime-window-time-invalid");

        Selected.Text = Loc.GetString("playtime-window-selected", ("count", jobs.Count + (Overall.Pressed ? 1 : 0)));

        AddButton.Disabled = !loaded || !valid || trackers.Count == 0;
        SetButton.Disabled = !loaded || !valid || trackers.Count == 0;
        MeetButton.Disabled = !loaded || jobs.Count == 0;
    }

    private void Change(bool overwrite)
    {
        if (_trackers == null || !PlayTimeTrackingShared.TryParseTime(TimeInput.Text, out var time))
            return;

        var trackers = SelectedTrackers();
        if (trackers.Count > 0)
            OnChange?.Invoke(trackers, time, overwrite);
    }

    private void MeetRequirements()
    {
        var jobs = SelectedJobs();
        if (_trackers != null && jobs.Count > 0)
            OnMeetRequirements?.Invoke(jobs.Select(job => new ProtoId<JobPrototype>(job.ID)).ToList());
    }
}
