using System.Linq;
using Content.Client._Crescent.Economy;
using Content.Shared._Crescent.Economy;
using Content.Shared._Crescent.Factions;
using Content.Client.UserInterface.Controls;
using Content.Shared.Shipyard.Prototypes;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using static Robust.Client.UserInterface.Controls.BaseButton;
using Content.Shared.Shipyard;

namespace Content.Client.Shipyard.UI;

[GenerateTypedNameReferences]
public sealed partial class ShipyardConsoleMenu : FancyWindow
{
    [Dependency] private readonly IPrototypeManager _protoManager = default!;

    public event Action<ButtonEventArgs>? OnSellShip;
    public event Action<string, string?>? OnPurchased;

    public PaymentSource Source { get; private set; } = PaymentSource.Faction;

    private ShipyardConsoleInterfaceState? _lastState;
    private readonly ShipyardConsoleBoundUserInterface _menu;
    private readonly EconomyPriceSystem _economy;
    private readonly List<string> _categoryStrings = new();
    private string? _category;

    private List<string> _lastProtos = new();
    private string _lastType = "";

    public ShipyardConsoleMenu(ShipyardConsoleBoundUserInterface owner)
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _menu = owner;
        _economy = IoCManager.Resolve<IEntityManager>().System<EconomyPriceSystem>();
        _economy.PricesUpdated += OnPricesUpdated;
        Title = Loc.GetString("shipyard-console-menu-title");
        SearchBar.OnTextChanged += OnSearchBarTextChanged;
        Categories.OnItemSelected += OnCategoryItemSelected;
        SellShipButton.OnPressed += (args) => { OnSellShip?.Invoke(args); };
        TreasuryButton.OnPressed += _ => PickSource(PaymentSource.Faction);
        PersonalButton.OnPressed += _ => PickSource(PaymentSource.Personal);
    }

    private void PickSource(PaymentSource source)
    {
        Source = source;
        if (_lastState != null)
            UpdatePayment(_lastState);
    }

    private void UpdatePayment(ShipyardConsoleInterfaceState state)
    {
        var factionYard = state.TreasuryFaction != null;
        PaymentRow.Visible = factionYard;

        if (!factionYard)
        {
            BalanceLabel.Text = Loc.GetString("cargo-console-menu-points-amount", ("amount", state.Balance.ToString()));
            return;
        }

        if (Source == PaymentSource.Personal && !state.HasPersonalAccount)
            Source = PaymentSource.Faction;

        TreasuryButton.Text = Loc.GetString("shipyard-console-pay-treasury",
            ("faction", FactionDisplay.Abbreviation(state.TreasuryFaction!)),
            ("balance", state.TreasuryBalance));
        TreasuryButton.Pressed = Source == PaymentSource.Faction;

        PersonalButton.Text = state.HasPersonalAccount
            ? Loc.GetString("shipyard-console-pay-personal", ("balance", state.PersonalBalance))
            : Loc.GetString("shipyard-console-pay-personal-none");
        PersonalButton.Disabled = !state.HasPersonalAccount;
        PersonalButton.Pressed = Source == PaymentSource.Personal;

        var balance = Source == PaymentSource.Faction ? state.TreasuryBalance : state.PersonalBalance;
        BalanceLabel.Text = Loc.GetString("cargo-console-menu-points-amount", ("amount", balance.ToString()));
    }


    private void OnCategoryItemSelected(OptionButton.ItemSelectedEventArgs args)
    {
        SetCategoryText(args.Id);
        PopulateProducts(_lastProtos, _lastType);
    }

    private void OnSearchBarTextChanged(LineEdit.LineEditEventArgs args)
    {
        PopulateProducts(_lastProtos, _lastType);
    }

    private void SetCategoryText(int id)
    {
        _category = id == 0 ? null : _categoryStrings[id];
        Categories.SelectId(id);
    }

    /// <summary>
    ///     Populates the list of products that will actually be shown, using the current filters.
    /// </summary>
    public void PopulateProducts(List<string> prototypes, string type)
    {
        Vessels.RemoveAllChildren();

        var newVessels = prototypes.Select(it => _protoManager.TryIndex<VesselPrototype>(it, out var proto) ? proto : null)
            .Where(it => it != null)
            .ToList();

        newVessels.Sort((x, y) =>
            string.Compare(x!.Name, y!.Name, StringComparison.CurrentCultureIgnoreCase));

        var search = SearchBar.Text.Trim().ToLowerInvariant();

        foreach (var prototype in newVessels)
        {
            if (prototype is null)
                continue;
            // if no search or category
            // else if search
            // else if category and not search
            if (search.Length == 0 && _category == null ||
                search.Length != 0 && prototype!.Name.ToLowerInvariant().Contains(search) ||
                search.Length == 0 && _category != null && prototype!.Category.Equals(_category))
            {
                var vesselEntry = new VesselRow(prototype, true);
                vesselEntry.OnPurchasePressed += (customName) => { OnPurchased?.Invoke(prototype.ID, customName); };
                Vessels.AddChild(vesselEntry);
            }
        }

        _lastProtos = prototypes;
        _lastType = type;
    }

    /// <summary>
    ///     Populates the list categories that will actually be shown, using the current filters.
    /// </summary>
    public void PopulateCategories()
    {
        _categoryStrings.Clear();
        Categories.Clear();
        var vessels = _protoManager.EnumeratePrototypes<VesselPrototype>();
        foreach (var prototype in vessels)
        {
            if (!_categoryStrings.Contains(prototype.Category))
            {
                _categoryStrings.Add(Loc.GetString(prototype.Category));
            }
        }

        _categoryStrings.Sort();

        // Add "All" category at the top of the list
        _categoryStrings.Insert(0, Loc.GetString("cargo-console-menu-populate-categories-all-text"));

        foreach (var str in _categoryStrings)
        {
            Categories.AddItem(str);
        }
    }

    public void UpdateState(ShipyardConsoleInterfaceState state)
    {
        _lastState = state;
        UpdatePayment(state);
        ShipAppraisalLabel.Text = Loc.GetString("cargo-console-menu-points-amount", ("amount", state.ShipSellValue.ToString()));
        SellShipButton.Disabled = state.ShipDeedTitle == null || !state.CanSell;
        TargetIdButton.Text = state.IsTargetIdPresent
            ? Loc.GetString("id-card-console-window-eject-button")
            : Loc.GetString("id-card-console-window-insert-button");
        if (state.ShipDeedTitle != null)
        {
            DeedTitle.Text = state.ShipDeedTitle;
        }
        else
        {
            DeedTitle.Text = $"None";
        }
    }

    protected override void Dispose(bool disposing)
    {
        base.Dispose(disposing);

        if (disposing)
            _economy.PricesUpdated -= OnPricesUpdated;
    }

    private void OnPricesUpdated()
    {
        if (_lastProtos.Count == 0)
            return;

        PopulateProducts(_lastProtos, _lastType);
    }
}
