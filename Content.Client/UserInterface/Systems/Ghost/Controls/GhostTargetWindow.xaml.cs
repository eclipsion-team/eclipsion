using System.Linq;
using System.Numerics;
using Content.Client.Stylesheets;
using Content.Shared.Ghost;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.UserInterface.Systems.Ghost.Controls
{
    [GenerateTypedNameReferences]
    public sealed partial class GhostTargetWindow : DefaultWindow
    {
        private List<(GhostWarpCategory Category, string Name, NetEntity Entity)> _warps = new();
        private string _searchText = string.Empty;

        private readonly List<(Label Heading, List<Button> Buttons)> _sections = new();

        public event Action<NetEntity>? WarpClicked;
        public event Action? OnGhostnadoClicked;

        public GhostTargetWindow()
        {
            RobustXamlLoader.Load(this);
            SearchBar.OnTextChanged += OnSearchTextChanged;

            GhostnadoButton.OnPressed += _ => OnGhostnadoClicked?.Invoke();
        }

        public void UpdateWarps(IEnumerable<GhostWarp> warps)
        {
            _warps = warps
                .OrderBy(w => w.Category)
                .ThenBy(w => w.DisplayName, Comparer<string>.Create(
                    (x, y) => string.Compare(x, y, StringComparison.Ordinal)))
                .Select(w =>
                {
                    var name = w.IsWarpPoint
                        ? Loc.GetString("ghost-target-window-current-button", ("name", w.DisplayName))
                        : w.DisplayName;

                    return (w.Category, name, w.Entity);
                })
                .ToList();
        }

        public void Populate()
        {
            ButtonContainer.DisposeAllChildren();
            _sections.Clear();
            AddButtons();
        }

        private void AddButtons()
        {
            foreach (var group in _warps.GroupBy(w => w.Category))
            {
                var heading = new Label
                {
                    Text = Loc.GetString($"ghost-target-window-category-{group.Key.ToString().ToLowerInvariant()}"),
                    StyleClasses = { StyleNano.StyleClassLabelHeading },
                    HorizontalAlignment = HAlignment.Center,
                    Margin = new Thickness(0, 6, 0, 0),
                };
                ButtonContainer.AddChild(heading);

                var buttons = new List<Button>();
                foreach (var (_, name, warpTarget) in group)
                {
                    var currentButtonRef = new Button
                    {
                        Text = name,
                        TextAlign = Label.AlignMode.Right,
                        HorizontalAlignment = HAlignment.Center,
                        VerticalAlignment = VAlignment.Center,
                        SizeFlagsStretchRatio = 1,
                        MinSize = new Vector2(340, 20),
                        ClipText = true,
                    };

                    currentButtonRef.OnPressed += _ => WarpClicked?.Invoke(warpTarget);
                    currentButtonRef.Visible = ButtonIsVisible(currentButtonRef);

                    ButtonContainer.AddChild(currentButtonRef);
                    buttons.Add(currentButtonRef);
                }

                heading.Visible = buttons.Any(button => button.Visible);
                _sections.Add((heading, buttons));
            }
        }

        private bool ButtonIsVisible(Button button)
        {
            return string.IsNullOrEmpty(_searchText) || button.Text == null || button.Text.Contains(_searchText, StringComparison.OrdinalIgnoreCase);
        }

        private void UpdateVisibleButtons()
        {
            foreach (var (heading, buttons) in _sections)
            {
                var any = false;
                foreach (var button in buttons)
                {
                    button.Visible = ButtonIsVisible(button);
                    any |= button.Visible;
                }

                heading.Visible = any;
            }
        }

        private void OnSearchTextChanged(LineEdit.LineEditEventArgs args)
        {
            _searchText = args.Text;

            UpdateVisibleButtons();
        }
    }
}
