using System.Linq;
using Content.Shared._Crescent.Factions;
using Content.Shared._Crescent.PoliticalMap;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client._Crescent.PoliticalMap;

[GenerateTypedNameReferences]
public sealed partial class PoliticalMapPanel : BoxContainer
{
    [Dependency] private readonly IEntityManager _entMan = default!;

    private readonly PoliticalMapSystem _system;
    private readonly SharedTransformSystem _transform;

    private PoliticalMapData? _data;

    private EntityUid? _viewer;

    public EntityUid? Viewer
    {
        get => _viewer;
        set
        {
            var legendChanges = (_viewer == null) != (value == null);
            _viewer = value;

            if (legendChanges && _data != null)
                UpdateLegend(_data);
        }
    }

    public PoliticalMapPanel()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _system = _entMan.System<PoliticalMapSystem>();
        _transform = _entMan.System<SharedTransformSystem>();

        Map.HoveredChanged += UpdateHover;
        UpdateHover(null);
    }

    protected override void EnteredTree()
    {
        base.EnteredTree();

        _system.Updated += SetData;
        if (_system.Data != null)
            SetData(_system.Data);

        _system.Request();
    }

    protected override void ExitedTree()
    {
        base.ExitedTree();

        _system.Updated -= SetData;
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        Map.ViewerPosition = Viewer is { } viewer && _entMan.TryGetComponent(viewer, out TransformComponent? xform)
            ? _transform.GetWorldPosition(xform)
            : null;
    }

    private void SetData(PoliticalMapData data)
    {
        _data = data;
        UpdateLegend(data);
        Map.SetData(data);
    }

    private void UpdateLegend(PoliticalMapData data)
    {
        LegendContainer.RemoveAllChildren();

        foreach (var group in data.Cells
                     .Where(cell => cell.Owner != null)
                     .GroupBy(cell => cell.Owner!)
                     .OrderByDescending(group => group.Count())
                     .ThenBy(group => group.Key, StringComparer.Ordinal))
        {
            LegendContainer.AddChild(LegendRow(Map.ColorOf(group.Key),
                Loc.GetString("political-map-legend-faction",
                    ("faction", FactionDisplay.Abbreviation(group.Key)),
                    ("count", group.Count()))));
        }

        var contested = data.Cells.Count(cell => cell.Contested);
        if (contested > 0)
        {
            LegendContainer.AddChild(LegendRow(Color.FromHex("#d9c05a"),
                Loc.GetString("political-map-legend-contested", ("count", contested))));
        }

        var unclaimed = data.Cells.Count(cell => cell.Owner == null && !cell.Contested);
        LegendContainer.AddChild(LegendRow(Color.FromHex("#3a3e4a"),
            Loc.GetString("political-map-legend-unclaimed", ("count", unclaimed))));

        if (Viewer != null)
            LegendContainer.AddChild(LegendRow(Color.Cyan, Loc.GetString("political-map-legend-viewer")));
    }

    private static BoxContainer LegendRow(Color color, string text)
    {
        var row = new BoxContainer { Orientation = LayoutOrientation.Horizontal, SeparationOverride = 6 };
        row.AddChild(new PanelContainer
        {
            SetSize = new System.Numerics.Vector2(14, 14),
            VerticalAlignment = VAlignment.Center,
            PanelOverride = new StyleBoxFlat { BackgroundColor = color },
        });
        row.AddChild(new Label { Text = text });
        return row;
    }

    private void UpdateHover(PoliticalMapCell? cell)
    {
        HoverAnchors.RemoveAllChildren();

        if (cell == null || _data == null)
        {
            HoverTitle.Text = Loc.GetString("political-map-hover-none");
            HoverRuler.Text = string.Empty;
            return;
        }

        HoverTitle.Text = Loc.GetString("political-map-hover-title", ("hex", Map.CellName(cell)));

        if (cell.Owner != null)
        {
            HoverRuler.Text = Loc.GetString("political-map-hover-ruler", ("faction", FactionDisplay.Abbreviation(cell.Owner)));
            HoverRuler.FontColorOverride = Map.ColorOf(cell.Owner);
        }
        else
        {
            HoverRuler.Text = Loc.GetString(cell.Contested ? "political-map-hover-contested" : "political-map-hover-unclaimed");
            HoverRuler.FontColorOverride = null;
        }

        var layout = _data.Layout;
        foreach (var anchor in _data.Anchors)
        {
            if (layout.CellAt(anchor.Position) != (cell.Q, cell.R))
                continue;

            var holder = anchor.Owner == null
                ? Loc.GetString("political-map-unclaimed")
                : FactionDisplay.Abbreviation(anchor.Owner);

            HoverAnchors.AddChild(new Label
            {
                Text = Loc.GetString(anchor.Kind == PoliticalMapAnchorKind.Station
                        ? "political-map-hover-station"
                        : "political-map-hover-territory",
                    ("name", anchor.Name),
                    ("holder", holder)),
                FontColorOverride = anchor.Owner == null ? null : Map.ColorOf(anchor.Owner),
                ClipText = true,
            });
        }

        if (HoverAnchors.ChildCount == 0)
            HoverAnchors.AddChild(new Label { Text = Loc.GetString("political-map-hover-empty"), StyleClasses = { "LabelSecondaryColor" } });
    }
}
