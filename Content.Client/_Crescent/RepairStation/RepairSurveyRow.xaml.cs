using Content.Client._Crescent.UI;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Crescent.RepairStation;

/// <summary>
/// One line of a repair survey: what the slip found, how much of it there is, and a bar drawing that
/// figure against the worst line on the same slip.
/// </summary>
/// <remarks>
/// The bar is what turns a column of numbers into a shape. A hull that is mostly mess and a hull that
/// is mostly holes read the same at a glance otherwise - both are seven figures in a list - and the
/// customer only cares which of the two he is looking at.
/// </remarks>
[GenerateTypedNameReferences]
public sealed partial class RepairSurveyRow : BoxContainer
{
    private readonly StyleBoxFlat _fill = new();

    public RepairSurveyRow()
    {
        RobustXamlLoader.Load(this);

        // The stock progress bar carries a 14.5px content margin on both edges, which is most of a
        // button's height. These are hairline meters sitting between two lines of text, so they bring
        // their own boxes rather than fight the sheet for the height back.
        Meter.BackgroundStyleBoxOverride = new StyleBoxFlat(Color.FromHex("#1B1B1F"));
        Meter.ForegroundStyleBoxOverride = _fill;
    }

    /// <summary>
    /// What the line is called. Set from XAML so the survey layout stays readable in one file.
    /// </summary>
    public string Title
    {
        get => TitleLabel.Text ?? string.Empty;
        set => TitleLabel.Text = value;
    }

    /// <param name="value">Count this line of the survey turned up.</param>
    /// <param name="worst">Largest count anywhere on the slip, which every bar is drawn against.</param>
    /// <param name="tint">Colour for a non-zero count. Amber unless the line is worth more alarm.</param>
    public void SetValue(int value, int worst, Color? tint = null)
    {
        var colour = value == 0 ? ConsolePalette.Muted : tint ?? ConsolePalette.Warn;

        ValueLabel.SetTextIfChanged(value.ToString());
        ValueLabel.FontColorOverride = colour;
        TitleLabel.FontColorOverride = value == 0 ? ConsolePalette.Muted : ConsolePalette.Normal;

        _fill.BackgroundColor = colour;
        Meter.Value = worst <= 0 ? 0f : Math.Clamp((float) value / worst, 0f, 1f);
    }
}
