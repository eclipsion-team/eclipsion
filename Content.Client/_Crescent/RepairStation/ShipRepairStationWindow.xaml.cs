using Content.Client._Crescent.UI;
using Content.Shared._Crescent.RepairStation;
using Content.Shared.Bank.Components;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.Player;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;
using FancyWindow = Content.Client.UserInterface.Controls.FancyWindow;

namespace Content.Client._Crescent.RepairStation;

[GenerateTypedNameReferences]
public sealed partial class ShipRepairStationWindow : FancyWindow
{
    [Dependency] private readonly IEntityManager _entMan = default!;
    [Dependency] private readonly IGameTiming _timing = default!;
    [Dependency] private readonly IPlayerManager _player = default!;

    public Action<NetEntity>? OnShipSelected;
    public Action? OnStartPressed;
    public Action? OnCancelPressed;
    public Action? OnSnapshotPressed;

    /// <summary>
    /// Dropdown entry order, so a selection can be turned back into a grid.
    /// </summary>
    private readonly List<NetEntity> _ships = new();

    /// <summary>
    /// The status strip and the blueprint warning are the only two panels that change colour, so they
    /// carry their own boxes rather than the one declared in XAML.
    /// </summary>
    private readonly StyleBoxFlat _statusBox = new();

    private readonly StyleBoxFlat _blueprintBox = new();

    private readonly StyleBoxFlat _workBarFill = new() { BackgroundColor = ConsolePalette.Good };

    private ShipRepairStationUiState? _state;

    public ShipRepairStationWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        // A left edge in the status colour, over a wash of the same. Reads as a lamp on the panel
        // without spending a line of the window on one.
        _statusBox.BorderThickness = new Thickness(3, 0, 0, 0);
        StatusPanel.PanelOverride = _statusBox;

        _blueprintBox.BorderThickness = new Thickness(3, 0, 0, 0);
        _blueprintBox.BorderColor = ConsolePalette.Warn;
        _blueprintBox.BackgroundColor = Wash(ConsolePalette.Warn);
        BlueprintPanel.PanelOverride = _blueprintBox;

        WorkBar.BackgroundStyleBoxOverride = new StyleBoxFlat(Color.FromHex("#1B1B1F"));
        WorkBar.ForegroundStyleBoxOverride = _workBarFill;

        // Set once rather than on every state push: it is one fixed sentence, and a rich label is what
        // wraps it inside the window instead of stretching the window to fit it.
        BlueprintLabel.SetMessage(Loc.GetString("ship-repair-station-no-blueprint-note"));

        ShipOption.OnItemSelected += args =>
        {
            ShipOption.SelectId(args.Id);
            if (args.Id >= 0 && args.Id < _ships.Count)
                OnShipSelected?.Invoke(_ships[args.Id]);
        };

        StartButton.OnPressed += _ => OnStartPressed?.Invoke();
        CancelButton.OnPressed += _ => OnCancelPressed?.Invoke();
        SnapshotButton.OnPressed += _ => OnSnapshotPressed?.Invoke();
    }

    /// <summary>
    /// The faint fill behind a coloured strip. Dark enough that the mono text on top stays the
    /// brightest thing in the panel.
    /// </summary>
    private static Color Wash(Color colour)
    {
        return new Color(colour.R, colour.G, colour.B, 0.14f);
    }

    /// <summary>
    /// The viewer's own balance, read locally rather than taken from the console's state.
    /// </summary>
    /// <remarks>
    /// The state is one object shared by everyone at the console, so it cannot carry a figure that is
    /// per-viewer. It used to try: the console filled it in for whoever had just clicked, and its
    /// once-a-second refresh - which has no actor behind it - then overwrote it with zero. That made
    /// the authorise button light up on selecting a ship and go dead again a moment later.
    /// </remarks>
    private long GetBalance()
    {
        return _player.LocalEntity is { } player
               && _entMan.TryGetComponent<BankAccountComponent>(player, out var bank)
            ? bank.Balance
            : 0;
    }

    public void UpdateState(ShipRepairStationUiState state)
    {
        _state = state;

        RebuildShipList(state);

        var repairing = state.Status == ShipRepairStatus.Repairing;

        UpdateStatus(state);

        SurveyPanel.Visible = !repairing;
        ProgressPanel.Visible = repairing;

        // The quote the job was authorised on is already paid, and the survey behind it is stale until
        // the slip lets go of the hull. Showing it as a live figure would read as a second bill.
        BillPanel.Visible = !repairing;

        // Said out loud rather than left to be read off a survey full of zeroes: without a file the
        // slip cannot put anything back, only tidy up and beat out what is still standing.
        BlueprintPanel.Visible = state.BlueprintMissing && !repairing;

        // Only the override slip may file a blueprint, and only of a hull it is not working on.
        SnapshotButton.Visible = state.CanSnapshot;
        SnapshotButton.SetDisabled(repairing || state.Selected == null);

        UpdateSurvey(state);

        ProgressTitleLabel.SetTextIfChanged(Loc.GetString("ship-repair-station-working",
            ("ship", state.RepairingName ?? string.Empty)));
        PartsProgressLabel.SetTextIfChanged(Loc.GetString("ship-repair-station-parts-progress",
            ("done", state.JobsDone),
            ("total", state.JobsTotal)));

        CancelButton.Disabled = !repairing;

        UpdateBalance();
        UpdateProgress();
    }

    /// <summary>
    /// The status strip and the word in the masthead, which are the same fact said at two lengths.
    /// </summary>
    private void UpdateStatus(ShipRepairStationUiState state)
    {
        var (text, slip, colour) = state.Status switch
        {
            ShipRepairStatus.NoShip => (
                Loc.GetString("ship-repair-station-status-no-ship"),
                Loc.GetString("ship-repair-station-state-empty"),
                ConsolePalette.Muted),
            ShipRepairStatus.NoBlueprint => (
                Loc.GetString("ship-repair-station-status-no-blueprint"),
                Loc.GetString("ship-repair-station-state-unfiled"),
                ConsolePalette.Bad),
            ShipRepairStatus.Intact => (
                Loc.GetString("ship-repair-station-status-intact"),
                Loc.GetString("ship-repair-station-state-sound"),
                ConsolePalette.Good),
            ShipRepairStatus.Busy => (
                Loc.GetString("ship-repair-station-status-busy"),
                Loc.GetString("ship-repair-station-state-booked"),
                ConsolePalette.Bad),
            ShipRepairStatus.Repairing => (
                Loc.GetString("ship-repair-station-status-repairing", ("ship", state.RepairingName ?? string.Empty)),
                Loc.GetString("ship-repair-station-state-working"),
                ConsolePalette.Good),
            _ => (
                Loc.GetString("ship-repair-station-status-quoted"),
                Loc.GetString("ship-repair-station-state-quoted"),
                ConsolePalette.Warn),
        };

        StatusLabel.SetTextIfChanged(text);
        StatusLabel.FontColorOverride = colour;

        SlipStateLabel.SetTextIfChanged(slip);
        SlipStateLabel.FontColorOverride = colour;

        _statusBox.BorderColor = colour;
        _statusBox.BackgroundColor = Wash(colour);
    }

    /// <summary>
    /// Every line of the survey, with the bars drawn against the worst of them - so a hull that is all
    /// mess and a hull that is all holes do not read as the same column of numbers.
    /// </summary>
    private void UpdateSurvey(ShipRepairStationUiState state)
    {
        var cleaning = state.Spills + state.Debris;

        var worst = Math.Max(state.MissingTiles,
            Math.Max(state.StrippedTiles,
                Math.Max(state.MissingParts,
                    Math.Max(state.DamagedParts,
                        Math.Max(state.Decals,
                            Math.Max(cleaning, state.Restocks))))));

        // Decking open to space is the one line worth alarming over; the rest is work, not danger.
        TilesRow.SetValue(state.MissingTiles, worst, ConsolePalette.Bad);
        StrippedRow.SetValue(state.StrippedTiles, worst);
        PartsRow.SetValue(state.MissingParts, worst);
        DamagedRow.SetValue(state.DamagedParts, worst);
        DecalsRow.SetValue(state.Decals, worst);

        // Mopping and sweeping are one line on the slip; the customer is not interested in which of
        // the two the yard spent its time on.
        CleaningRow.SetValue(cleaning, worst);
        RestockRow.SetValue(state.Restocks, worst);

        var total = state.MissingTiles + state.StrippedTiles + state.MissingParts + state.DamagedParts
                    + state.Decals + cleaning + state.Restocks;

        WorkItemsLabel.SetTextIfChanged(total.ToString());

        // A zero is only good news when the slip actually looked at a hull. With nothing in the clamps,
        // or nothing to compare a hull against, the same zero means it has not been told anything.
        WorkItemsLabel.FontColorOverride = total != 0
            ? ConsolePalette.Normal
            : state.Status == ShipRepairStatus.Intact
                ? ConsolePalette.Good
                : ConsolePalette.Muted;
    }

    /// <summary>
    /// Only touched when the ship list actually changes, so a once-a-second state push cannot collapse
    /// the dropdown out from under whoever has it open.
    /// </summary>
    private void RebuildShipList(ShipRepairStationUiState state)
    {
        var same = _ships.Count == state.Docked.Count;
        if (same)
        {
            for (var i = 0; i < _ships.Count; i++)
            {
                if (_ships[i] == state.Docked[i].Grid)
                    continue;

                same = false;
                break;
            }
        }

        if (!same)
        {
            _ships.Clear();
            ShipOption.Clear();

            for (var i = 0; i < state.Docked.Count; i++)
            {
                var entry = state.Docked[i];
                var label = entry.HasBlueprint
                    ? entry.Name
                    : Loc.GetString("ship-repair-station-ship-unregistered", ("ship", entry.Name));

                ShipOption.AddItem(label, i);
                _ships.Add(entry.Grid);
            }
        }

        ShipOption.Disabled = _ships.Count == 0;

        if (state.Selected is not { } selected)
            return;

        var index = _ships.IndexOf(selected);
        if (index >= 0)
            ShipOption.SelectId(index);
    }

    private void UpdateBalance()
    {
        if (_state is not { } state)
            return;

        // A slip working for nothing has no use for the viewer's account, and an admin looking out of
        // a ghost has none to show.
        BalanceRow.Visible = !state.Free;

        var balance = GetBalance();
        var affordable = state.Free || state.Quote <= balance;

        BalanceLabel.SetTextIfChanged(Loc.GetString("ship-repair-station-credits", ("amount", balance)));
        BalanceLabel.FontColorOverride = affordable ? ConsolePalette.Normal : ConsolePalette.Bad;

        QuoteLabel.SetTextIfChanged(state.Free
            ? Loc.GetString("ship-repair-station-no-charge")
            : Loc.GetString("ship-repair-station-credits", ("amount", state.Quote)));

        QuoteLabel.FontColorOverride = state.Free
            ? ConsolePalette.Good
            : affordable
                ? ConsolePalette.Normal
                : ConsolePalette.Bad;

        StartButton.SetDisabled(state.Status != ShipRepairStatus.Quoted || !affordable,
            affordable ? null : Loc.GetString("ship-repair-station-cannot-afford"));
    }

    /// <summary>
    /// Runs off the clock rather than the state pushes, so the bar creeps and the ETA counts down
    /// smoothly between them.
    /// </summary>
    private void UpdateProgress()
    {
        if (_state is not { Status: ShipRepairStatus.Repairing } state)
            return;

        var span = state.EndTime - state.StartTime;
        var elapsed = _timing.CurTime - state.StartTime;

        var fraction = span.TotalSeconds <= 0
            ? 1f
            : Math.Clamp((float) (elapsed.TotalSeconds / span.TotalSeconds), 0f, 1f);

        WorkBar.Value = fraction;
        PercentLabel.SetTextIfChanged(Loc.GetString("ship-repair-station-percent",
            ("percent", (int) MathF.Round(fraction * 100f))));

        var remaining = state.EndTime - _timing.CurTime;
        if (remaining < TimeSpan.Zero)
            remaining = TimeSpan.Zero;

        EtaLabel.SetTextIfChanged(Loc.GetString("ship-repair-station-eta",
            ("time", $"{(int) remaining.TotalMinutes:0}:{remaining.Seconds:00}")));
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        UpdateBalance();
        UpdateProgress();
    }
}
