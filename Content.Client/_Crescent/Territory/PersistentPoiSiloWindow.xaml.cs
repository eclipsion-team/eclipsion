using System.Linq;
using Content.Client.Message;
using Content.Client.UserInterface.Controls;
using Content.Shared._Crescent.Territory;
using Content.Shared.Stacks;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._Crescent.Territory;

[GenerateTypedNameReferences]
public sealed partial class PersistentPoiSiloWindow : FancyWindow
{
    [Dependency] private readonly IPrototypeManager _proto = default!;

    // zero is a full stack
    private static readonly int[] Amounts = { 1, 5, 10, 0 };

    public event Action<ProtoId<StackPrototype>, int>? OnEject;

    private readonly Dictionary<ProtoId<StackPrototype>, int> _shown = new();

    public PersistentPoiSiloWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        HintLabel.SetMarkup(Loc.GetString("persistent-poi-silo-ui-hint"));
    }

    public void Update(PersistentPoiMaterialSiloComponent silo)
    {
        var stored = silo.Stored.Where(pair => pair.Value > 0).ToDictionary(pair => pair.Key, pair => pair.Value);
        if (stored.Count == _shown.Count && stored.All(pair => _shown.GetValueOrDefault(pair.Key) == pair.Value))
            return;

        _shown.Clear();
        foreach (var (material, count) in stored)
        {
            _shown[material] = count;
        }

        MaterialList.RemoveAllChildren();
        EmptyLabel.Visible = stored.Count == 0;

        foreach (var (material, count) in stored.OrderBy(pair => Name(pair.Key)))
        {
            var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 4 };
            row.AddChild(new Label { Text = Name(material), HorizontalExpand = true, ClipText = true });
            row.AddChild(new Label { Text = count.ToString(), MinWidth = 50, Align = Label.AlignMode.Right });

            foreach (var amount in Amounts)
            {
                var button = new Button
                {
                    Text = amount == 0
                        ? Loc.GetString("persistent-poi-silo-ui-stack")
                        : amount.ToString(),
                    MinWidth = amount == 0 ? 56 : 36,
                    StyleClasses = { "OpenBoth" },
                    Disabled = amount > count,
                    ToolTip = amount == 0
                        ? Loc.GetString("persistent-poi-silo-ui-stack-tooltip")
                        : null,
                };

                var id = material;
                var take = amount;
                button.OnPressed += _ => OnEject?.Invoke(id, take);
                row.AddChild(button);
            }

            MaterialList.AddChild(row);
        }
    }

    private string Name(ProtoId<StackPrototype> material)
    {
        if (!_proto.TryIndex(material, out var stack))
            return material.Id;

        var name = Loc.GetString(stack.Name);
        return name.Length > 0 ? name.Substring(0, 1).ToUpperInvariant() + name.Substring(1) : name;
    }
}
