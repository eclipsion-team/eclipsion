using System.Linq;
using System.Numerics;
using Content.Client._Crescent.UI;
using Content.Client.Message;
using Content.Client.UserInterface.Controls;
using Content.Shared._Crescent.Territory;
using Content.Shared.Construction.Prototypes;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Timing;
using Robust.Shared.Utility;

namespace Content.Client._Crescent.Territory;

[GenerateTypedNameReferences]
public sealed partial class PersistentPoiBuildWindow : FancyWindow
{
    [Dependency] private readonly IEntityManager _entMan = default!;
    [Dependency] private readonly IPrototypeManager _proto = default!;

    private static readonly Color Ready = Color.FromHex("#7FD67A");
    private static readonly Color Short = Color.FromHex("#E8B33D");
    private static readonly Color Missing = Color.FromHex("#E05A5A");
    private static readonly Color Muted = Color.FromHex("#9A9AA4");

    private const float RefreshInterval = 0.5f;

    private readonly PersistentPoiBuildSystem _build;
    private readonly SpriteSystem _sprite;

    public event Action<ConstructionPrototype>? OnBuild;
    public event Action? OnPaint;

    private List<PersistentPoiBuildCategory> _categories = new();
    private readonly List<Button> _categoryButtons = new();
    private readonly List<(ConstructionPrototype Recipe, Button Button, Label Status, Label Cost)> _rows = new();

    private int _category;
    private ConstructionPrototype? _selected;
    private float _sinceRefresh;

    public PersistentPoiBuildWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _build = _entMan.System<PersistentPoiBuildSystem>();
        _sprite = _entMan.System<SpriteSystem>();

        PaintIcon.Texture = _sprite.Frame0(new SpriteSpecifier.Rsi(new ResPath("Objects/Tools/spray_painter.rsi"), "spray_painter"));
        FooterLabel.SetHint(Loc.GetString("persistent-poi-build-ui-footer"));
        PaintButton.OnPressed += _ => OnPaint?.Invoke();
        BuildButton.OnPressed += _ =>
        {
            if (_selected != null)
                OnBuild?.Invoke(_selected);
        };
        SearchBar.OnTextChanged += _ => RebuildRecipes();
    }

    public void Populate(List<PersistentPoiBuildCategory> categories)
    {
        _categories = categories;
        _categoryButtons.Clear();
        CategoryList.RemoveAllChildren();

        for (var i = 0; i < _categories.Count; i++)
        {
            var index = i;
            var category = _categories[i];

            var button = new Button { ToggleMode = true, StyleClasses = { "OpenBoth" }, HorizontalExpand = true };
            var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 6 };
            row.AddChild(new TextureRect
            {
                Texture = _sprite.Frame0(category.Icon),
                Stretch = TextureRect.StretchMode.KeepAspectCentered,
                SetSize = new Vector2(24, 24),
            });
            row.AddChild(new Label
            {
                Text = Loc.GetString(category.Name),
                VerticalAlignment = VAlignment.Center,
                HorizontalExpand = true,
                ClipText = true,
            });
            button.AddChild(row);
            button.OnPressed += _ => SelectCategory(index);

            CategoryList.AddChild(button);
            _categoryButtons.Add(button);
        }

        SelectCategory(0);
    }

    private void SelectCategory(int index)
    {
        _category = Math.Clamp(index, 0, Math.Max(0, _categories.Count - 1));
        for (var i = 0; i < _categoryButtons.Count; i++)
        {
            _categoryButtons[i].Pressed = i == _category;
        }

        RebuildRecipes();
    }

    private void RebuildRecipes()
    {
        RecipeList.RemoveAllChildren();
        _rows.Clear();

        var search = SearchBar.Text.Trim();
        var recipes = new List<ConstructionPrototype>();
        var pages = search.Length > 0 ? _categories : _categories.Skip(_category).Take(1);
        foreach (var category in pages)
        {
            foreach (var id in category.Recipes)
            {
                if (!_proto.TryIndex(id, out var recipe) || recipes.Contains(recipe))
                    continue;

                if (search.Length > 0 && !recipe.Name.Contains(search, StringComparison.OrdinalIgnoreCase))
                    continue;

                if (_build.GetStatus(recipe).Block == PersistentPoiBuildBlock.OtherFaction)
                    continue;

                recipes.Add(recipe);
            }
        }

        foreach (var recipe in recipes)
        {
            var button = new Button { ToggleMode = true, StyleClasses = { "OpenBoth" }, HorizontalExpand = true };
            var row = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                SeparationOverride = 8,
                Margin = new Thickness(2),
            };
            row.AddChild(RecipeIcon(recipe, 40));

            var text = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Vertical,
                HorizontalExpand = true,
                VerticalAlignment = VAlignment.Center,
            };
            text.AddChild(new Label { Text = Capitalize(recipe.Name), ClipText = true });
            var cost = new Label { StyleClasses = { "LabelSubText" }, ClipText = true };
            text.AddChild(cost);
            row.AddChild(text);

            var status = new Label { VerticalAlignment = VAlignment.Center, Align = Label.AlignMode.Right, MinWidth = 70 };
            row.AddChild(status);

            button.AddChild(row);
            button.OnPressed += _ => Select(recipe);

            RecipeList.AddChild(button);
            _rows.Add((recipe, button, status, cost));
        }

        if (recipes.Count == 0)
        {
            RecipeList.AddChild(new Label
            {
                Text = Loc.GetString(search.Length > 0 ? "persistent-poi-build-ui-no-match" : "persistent-poi-build-ui-empty-page"),
                StyleClasses = { "LabelSubText" },
                Margin = new Thickness(4),
            });
        }

        if (_selected == null || !recipes.Contains(_selected))
            _selected = recipes.FirstOrDefault();

        Refresh();
    }

    private void Select(ConstructionPrototype recipe)
    {
        _selected = recipe;
        Refresh();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        _sinceRefresh += args.DeltaSeconds;
        if (_sinceRefresh < RefreshInterval)
            return;

        _sinceRefresh = 0f;
        Refresh();
    }

    private void Refresh()
    {
        RefreshHeader();

        foreach (var (recipe, button, status, cost) in _rows)
        {
            var recipeStatus = _build.GetStatus(recipe);
            button.Pressed = recipe == _selected;
            button.Modulate = recipeStatus.Block == PersistentPoiBuildBlock.None ? Color.White : Muted;

            status.Text = ShortStatus(recipeStatus);
            status.FontColorOverride = recipeStatus.Block == PersistentPoiBuildBlock.None ? Ready : Missing;

            cost.Text = string.Join("  ·  ", _build.GetCosts(recipe)
                .GroupBy(c => c.Material.ID)
                .Select(g => $"{g.Sum(c => c.Amount)} {g.First().Material.Name}"));
        }

        RefreshDetails();
    }

    private void RefreshHeader()
    {
        if (!_build.TryGetTerritory(out var territory))
        {
            TerritoryLabel.Text = Loc.GetString("persistent-poi-build-ui-no-territory");
            SummaryLabel.Text = string.Empty;
            BannerIcon.Texture = null;
            return;
        }

        TerritoryLabel.Text = _entMan.GetComponent<MetaDataComponent>(territory).EntityName;

        var line = territory.Comp.Capability is { } capability && _proto.TryIndex(capability, out var capabilityProto)
            ? Loc.GetString("persistent-poi-build-ui-line", ("line", Loc.GetString(capabilityProto.Name)))
            : Loc.GetString("persistent-poi-build-ui-no-line");

        SummaryLabel.Text = Loc.GetString("persistent-poi-build-ui-summary",
            ("level", territory.Comp.Level),
            ("max", _build.MaxLevel),
            ("line", line));

        BannerIcon.Texture = _build.GetBanner(territory) is { } banner ? _sprite.Frame0(banner) : null;
    }

    private void RefreshDetails()
    {
        DetailStages.RemoveAllChildren();

        DetailIcon.RemoveAllChildren();

        if (_selected is not { } recipe)
        {
            DetailName.SetMessage(string.Empty);
            DetailStatus.SetMessage(string.Empty);
            DetailDescription.SetMessage(Loc.GetString("persistent-poi-build-ui-pick"));
            DetailLimit.SetMessage(string.Empty);
            StagesHeader.Visible = false;
            BuildButton.Disabled = true;
            return;
        }

        var status = _build.GetStatus(recipe);

        DetailIcon.AddChild(RecipeIcon(recipe, 64));
        DetailName.SetMarkup($"[bold]{FormattedMessage.EscapeText(Capitalize(recipe.Name))}[/bold]");
        DetailStatus.SetMarkup(LongStatus(status));
        DetailDescription.SetMessage(recipe.Description);

        var stages = _build.GetStages(recipe);
        StagesHeader.Visible = stages.Count > 0;
        for (var i = 0; i < stages.Count; i++)
        {
            DetailStages.AddChild(BuildStage(i + 1, stages.Count, stages[i]));
        }

        DetailLimit.SetMarkup(LimitText(status));
        BuildButton.Disabled = status.Block != PersistentPoiBuildBlock.None;
    }

    private Control BuildStage(int number, int total, List<PersistentPoiBuildCost> costs)
    {
        var box = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, SeparationOverride = 2 };

        if (total > 1)
        {
            box.AddChild(new Label
            {
                Text = Loc.GetString(number == 1 ? "persistent-poi-build-ui-stage-first" : "persistent-poi-build-ui-stage-next",
                    ("number", number)),
                StyleClasses = { "LabelSubText" },
            });
        }

        foreach (var cost in costs)
        {
            var carried = _build.CountCarried(cost.Material.ID, cost.Amount);
            var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 6 };
            row.AddChild(new TextureRect
            {
                Texture = _sprite.Frame0(cost.Material.Icon ?? SpriteSpecifier.Invalid),
                Stretch = TextureRect.StretchMode.KeepAspectCentered,
                SetSize = new Vector2(24, 24),
            });
            row.AddChild(new Label
            {
                Text = $"{cost.Amount} {cost.Material.Name}",
                HorizontalExpand = true,
                VerticalAlignment = VAlignment.Center,
                ClipText = true,
            });

            var (color, key) = carried.LargestStack >= cost.Amount
                ? (Ready, "persistent-poi-build-ui-carried")
                : carried.Total >= cost.Amount
                    ? (Short, "persistent-poi-build-ui-carried-split")
                    : (Missing, "persistent-poi-build-ui-carried");

            row.AddChild(new Label
            {
                Text = Loc.GetString(key, ("count", carried.Total)),
                FontColorOverride = color,
                VerticalAlignment = VAlignment.Center,
            });
            box.AddChild(row);
        }

        return box;
    }

    private Control RecipeIcon(ConstructionPrototype recipe, float size)
    {
        var icon = new Control { SetSize = new Vector2(size, size), VerticalAlignment = VAlignment.Center };
        foreach (var layer in recipe.Layers)
        {
            icon.AddChild(new TextureRect
            {
                Texture = _sprite.Frame0(layer),
                Stretch = TextureRect.StretchMode.KeepAspectCentered,
            });
        }

        return icon;
    }

    private static string ShortStatus(PersistentPoiRecipeStatus status)
    {
        return status.Block switch
        {
            PersistentPoiBuildBlock.NotHeld => Loc.GetString("persistent-poi-build-ui-short-not-held"),
            PersistentPoiBuildBlock.WrongLine => Loc.GetString("persistent-poi-build-ui-short-wrong-line"),
            PersistentPoiBuildBlock.NeedsLevel => Loc.GetString("persistent-poi-build-ui-short-level", ("level", status.Level ?? 0)),
            PersistentPoiBuildBlock.LimitReached => Loc.GetString("persistent-poi-build-ui-short-full",
                ("count", status.Count), ("limit", status.Limit ?? 0)),
            _ => status.Limit is { } limit
                ? Loc.GetString("persistent-poi-build-ui-short-used", ("count", status.Count), ("limit", limit))
                : string.Empty,
        };
    }

    private string LongStatus(PersistentPoiRecipeStatus status)
    {
        return status.Block switch
        {
            PersistentPoiBuildBlock.NotHeld => Loc.GetString("persistent-poi-build-ui-status-not-held"),
            PersistentPoiBuildBlock.WrongLine => Loc.GetString("persistent-poi-build-ui-status-wrong-line",
                ("line", status.Line is { } line && _proto.TryIndex(line, out var lineProto) ? Loc.GetString(lineProto.Name) : string.Empty)),
            PersistentPoiBuildBlock.NeedsLevel => Loc.GetString("persistent-poi-build-ui-status-level", ("level", status.Level ?? 0)),
            PersistentPoiBuildBlock.LimitReached => status.Level is { } next
                ? Loc.GetString("persistent-poi-build-ui-status-full-next", ("level", next))
                : Loc.GetString("persistent-poi-build-ui-status-full"),
            _ => Loc.GetString("persistent-poi-build-ui-status-ready"),
        };
    }

    private string LimitText(PersistentPoiRecipeStatus status)
    {
        if (status.Category is not { } category)
            return Loc.GetString("persistent-poi-build-ui-unlimited");

        var name = Loc.GetString($"persistent-poi-category-{category.ToString().ToLowerInvariant()}");
        return status.Limit is { } limit
            ? Loc.GetString("persistent-poi-build-ui-limit", ("category", name), ("count", status.Count), ("limit", limit))
            : Loc.GetString("persistent-poi-build-ui-limit-unlimited", ("category", name), ("count", status.Count));
    }

    private static string Capitalize(string text)
    {
        return text.Length == 0 ? text : text[..1].ToUpperInvariant() + text[1..];
    }
}
