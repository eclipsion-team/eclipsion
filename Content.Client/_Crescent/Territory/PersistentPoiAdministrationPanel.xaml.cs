using System.Linq;
using Content.Client._Crescent.UI;
using Content.Client.UserInterface.Controls;
using Content.Shared._Crescent.Factions;
using Content.Shared._Crescent.Territory;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.Player;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Network;

namespace Content.Client._Crescent.Territory;

[GenerateTypedNameReferences]
public sealed partial class PersistentPoiAdministrationPanel : BoxContainer
{
    public event Action? OnUpgrade;
    public event Action? OnDraw;
    public event Action<string, bool>? OnReturn;
    public event Action<string>? OnRename;
    public event Action<bool>? OnSetDrones;
    public event Action<NetEntity>? OnAddMember;
    public event Action<NetUserId>? OnRemoveMember;
    public event Action<NetUserId, bool>? OnSetCoOwner;

    [Dependency] private readonly IPlayerManager _player = default!;

    private string? _shownName;
    private bool _dronesOff;
    private string? _shownMembers;

    public PersistentPoiAdministrationPanel()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        DepositHint.SetHint(Loc.GetString("persistent-poi-admin-ui-deposit-hint"));
        MembersHint.SetHint(Loc.GetString("persistent-poi-admin-ui-members-hint"));
        DronesButton.OnPressed += _ => OnSetDrones?.Invoke(!_dronesOff);

        UpgradeButton.OnPressed += _ => OnUpgrade?.Invoke();
        DrawButton.OnPressed += _ => OnDraw?.Invoke();

        RenameButton.OnPressed += _ => OnRename?.Invoke(NameEdit.Text);
        NameEdit.OnTextEntered += args => OnRename?.Invoke(args.Text);
        ResetNameButton.OnPressed += _ =>
        {
            NameEdit.Text = string.Empty;
            OnRename?.Invoke(string.Empty);
        };
    }

    private bool _remote;

    public bool Remote
    {
        set
        {
            _remote = value;
            DepositHint.SetHint(Loc.GetString(value
                ? "persistent-poi-admin-ui-remote-deposit-hint"
                : "persistent-poi-admin-ui-deposit-hint"));
            UpgradeButton.Visible &= !value;
            DrawButton.Visible &= !value;
            RenameBox.Visible &= !value;
            DronesBox.Visible &= !value;
            MembersBox.Visible &= !value;
        }
    }

    public void UpdateState(PersistentPoiAdministrationState state)
    {
        RegionLabel.SetTextIfChanged(state.RegionName);
        LevelLabel.SetTextIfChanged(Loc.GetString("persistent-poi-admin-ui-level", ("level", state.Level), ("max", state.MaxLevel)));
        HolderLabel.SetTextIfChanged(state.Owner == null
            ? Loc.GetString("persistent-poi-production-ui-unclaimed")
            : Loc.GetString("persistent-poi-production-ui-holder", ("faction", FactionDisplay.Abbreviation(state.Owner))));
        CapabilityLabel.SetTextIfChanged(state.Capability == null
            ? Loc.GetString("persistent-poi-admin-ui-no-capability")
            : Loc.GetString("persistent-poi-admin-ui-capability", ("capability", state.Capability)));

        // the mainframe renames from its own Command tab
        RenameBox.Visible = !_remote && state.Owner != null;
        PrefixLabel.Text = state.Owner == null ? string.Empty : FactionDisplay.Abbreviation(state.Owner) + "-";

        var name = state.CustomName ?? string.Empty;
        if (name != _shownName && !NameEdit.HasKeyboardFocus())
        {
            NameEdit.Text = name;
            _shownName = name;
        }

        ResetNameButton.Disabled = state.CustomName == null;

        _dronesOff = state.DronesOff;
        DronesBox.Visible = !_remote && state.HasDrones;
        DronesLabel.Text = Loc.GetString(state.DronesOff ? "persistent-poi-admin-ui-drones-off" : "persistent-poi-admin-ui-drones-on");
        DronesLabel.FontColorOverride = state.DronesOff ? ConsolePalette.Warn : ConsolePalette.Good;
        DronesButton.Text = Loc.GetString(state.DronesOff ? "persistent-poi-admin-ui-drones-turn-on" : "persistent-poi-admin-ui-drones-turn-off");

        UpdateMembers(state);
        UpdateLimits(state);
        UpdateCost(state);
    }

    private void UpdateMembers(PersistentPoiAdministrationState state)
    {
        MembersBox.Visible = !_remote && state.Independent;
        if (!MembersBox.Visible)
            return;

        var me = _player.LocalSession?.UserId;
        var founder = me != null && me == state.Founder;
        var manager = founder || state.Members.Any(m => m.User == me && m.CoOwner);

        MembersHeader.Text = Loc.GetString("persistent-poi-admin-ui-members", ("count", state.Members.Count), ("max", state.MaxMembers));
        FounderLabel.Text = state.FounderName != null
            ? Loc.GetString("persistent-poi-admin-ui-founder", ("name", state.FounderName))
            : Loc.GetString("persistent-poi-admin-ui-founder-unknown");

        // state comes in every second, remaking the rows each time ate clicks on their buttons
        var rows = string.Join('|', state.Members.Select(m => $"{m.User}/{m.Name}/{m.CoOwner}")) + "#" +
                   string.Join('|', state.Candidates.Select(c => $"{c.Body}/{c.Name}")) + "#" +
                   $"{founder}/{manager}/{state.MaxMembers}";
        if (rows == _shownMembers)
            return;

        _shownMembers = rows;

        MembersList.RemoveAllChildren();
        if (state.Members.Count == 0)
        {
            MembersList.AddChild(new Label
            {
                Text = Loc.GetString("persistent-poi-admin-ui-no-members"),
                FontColorOverride = ConsolePalette.Muted,
            });
        }

        foreach (var member in state.Members)
        {
            var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 6 };
            row.AddChild(new Label { Text = member.Name, HorizontalExpand = true, ClipText = true, VerticalAlignment = VAlignment.Center });
            row.AddChild(new Label
            {
                Text = Loc.GetString(member.CoOwner ? "persistent-poi-admin-ui-co-owner" : "persistent-poi-admin-ui-member"),
                FontColorOverride = member.CoOwner ? ConsolePalette.Good : ConsolePalette.Muted,
                MinWidth = 70,
                VerticalAlignment = VAlignment.Center,
            });

            var user = member.User;
            if (founder)
            {
                var promote = new Button
                {
                    Text = Loc.GetString(member.CoOwner ? "persistent-poi-admin-ui-make-member" : "persistent-poi-admin-ui-make-co-owner"),
                    StyleClasses = { "OpenRight" },
                };
                var coOwner = !member.CoOwner;
                promote.OnPressed += _ => OnSetCoOwner?.Invoke(user, coOwner);
                row.AddChild(promote);
            }

            if (user == me || manager)
            {
                var remove = new Button
                {
                    Text = Loc.GetString(user == me ? "persistent-poi-admin-ui-leave" : "persistent-poi-admin-ui-remove"),
                    StyleClasses = { founder ? "OpenLeft" : "OpenBoth", "Caution" },
                };
                remove.OnPressed += _ => OnRemoveMember?.Invoke(user);
                row.AddChild(remove);
            }

            MembersList.AddChild(row);
        }

        AddBox.Visible = manager;
        CandidatesList.RemoveAllChildren();
        if (!manager)
            return;

        if (state.Candidates.Count == 0)
        {
            CandidatesList.AddChild(new Label
            {
                Text = Loc.GetString("persistent-poi-admin-ui-no-candidates"),
                FontColorOverride = ConsolePalette.Muted,
            });
        }

        var full = state.Members.Count >= state.MaxMembers;
        foreach (var candidate in state.Candidates)
        {
            var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 6 };
            row.AddChild(new Label { Text = candidate.Name, HorizontalExpand = true, ClipText = true, VerticalAlignment = VAlignment.Center });

            var body = candidate.Body;
            var add = new Button
            {
                Text = Loc.GetString("persistent-poi-admin-ui-add"),
                StyleClasses = { "OpenBoth" },
                Disabled = full,
            };
            add.OnPressed += _ => OnAddMember?.Invoke(body);
            row.AddChild(add);

            CandidatesList.AddChild(row);
        }
    }

    private void UpdateLimits(PersistentPoiAdministrationState state)
    {
        LimitsGrid.RemoveAllChildren();

        foreach (var limit in state.Limits)
        {
            var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 12 };
            LimitsGrid.AddChild(row);

            row.AddChild(new Label
            {
                Text = Loc.GetString($"persistent-poi-category-{limit.Category.ToString().ToLowerInvariant()}"),
                HorizontalExpand = true,
            });

            var used = new Label
            {
                Text = limit.Limit is { } cap
                    ? Loc.GetString("persistent-poi-admin-ui-used", ("used", limit.Used), ("limit", cap))
                    : Loc.GetString("persistent-poi-admin-ui-used-unlimited", ("used", limit.Used)),
                FontColorOverride = limit.Limit is { } max && limit.Used > max ? ConsolePalette.Warn : ConsolePalette.Normal,
                MinWidth = 60,
                Align = Label.AlignMode.Right,
            };
            row.AddChild(used);

            row.AddChild(new Label
            {
                Text = limit.NextLimit is { } next && next != limit.Limit
                    ? Loc.GetString("persistent-poi-admin-ui-next-limit", ("limit", next))
                    : string.Empty,
                FontColorOverride = ConsolePalette.Good,
                MinWidth = 110,
            });
        }
    }

    private void UpdateCost(PersistentPoiAdministrationState state)
    {
        CostContainer.RemoveAllChildren();

        var atTop = state.Level >= state.MaxLevel;
        NextLevelHeader.Text = atTop
            ? Loc.GetString("persistent-poi-admin-ui-top-level")
            : Loc.GetString("persistent-poi-admin-ui-next-level", ("level", state.Level + 1));
        DepositHint.Visible = !atTop;
        UpgradeButton.Visible = !atTop && !_remote;
        UpgradeButton.Disabled = !state.CanUpgrade;
        UpgradeButton.Text = Loc.GetString("persistent-poi-admin-ui-upgrade", ("level", state.Level + 1));
        DrawButton.Visible = !atTop && !_remote;
        DrawButton.Disabled = !state.HasSilo ||
                              !state.NextLevelCost.Any(cost => cost.InSilo > 0 && cost.Deposited < cost.Required);

        foreach (var cost in state.NextLevelCost)
        {
            var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 8 };
            var complete = cost.Deposited >= cost.Required;

            var material = cost.Material.Length > 0
                ? cost.Material.Substring(0, 1).ToUpperInvariant() + cost.Material.Substring(1)
                : cost.Material;
            row.AddChild(new Label { Text = material, MinWidth = 130, ClipText = true });
            row.AddChild(new ProgressBar
            {
                MinValue = 0f,
                MaxValue = 1f,
                Value = cost.Required <= 0 ? 1f : Math.Clamp((float) cost.Deposited / cost.Required, 0f, 1f),
                HorizontalExpand = true,
                SetHeight = 10,
                VerticalAlignment = VAlignment.Center,
                BackgroundStyleBoxOverride = new StyleBoxFlat(Color.FromHex("#2a2a30")),
                ForegroundStyleBoxOverride = new StyleBoxFlat(complete ? ConsolePalette.Good : ConsolePalette.Warn),
            });
            row.AddChild(new Label
            {
                Text = Loc.GetString("persistent-poi-admin-ui-deposited", ("deposited", cost.Deposited), ("required", cost.Required)),
                MinWidth = 90,
                Align = Label.AlignMode.Right,
                FontColorOverride = complete ? ConsolePalette.Good : ConsolePalette.Normal,
            });

            if (!_remote)
            {
                row.AddChild(new Label
                {
                    Text = state.HasSilo ? Loc.GetString("persistent-poi-admin-ui-in-silo", ("count", cost.InSilo)) : string.Empty,
                    MinWidth = 70,
                    Align = Label.AlignMode.Right,
                    FontColorOverride = ConsolePalette.Muted,
                });

                var id = cost.MaterialId;
                var take = new Button
                {
                    Text = Loc.GetString("persistent-poi-admin-ui-take"),
                    ToolTip = Loc.GetString("persistent-poi-admin-ui-take-tooltip"),
                    StyleClasses = { "OpenRight" },
                    Disabled = cost.Deposited <= 0,
                };
                take.OnPressed += _ => OnReturn?.Invoke(id, false);
                row.AddChild(take);

                var toSilo = new Button
                {
                    Text = Loc.GetString("persistent-poi-admin-ui-to-silo"),
                    ToolTip = Loc.GetString("persistent-poi-admin-ui-to-silo-tooltip"),
                    StyleClasses = { "OpenLeft" },
                    Disabled = cost.Deposited <= 0 || !state.HasSilo,
                };
                toSilo.OnPressed += _ => OnReturn?.Invoke(id, true);
                row.AddChild(toSilo);
            }

            CostContainer.AddChild(row);
        }
    }
}
