using Content.Client._Crescent.UI;
using Content.Client.UserInterface.Controls;
using Content.Shared._Crescent.Economy;
using Content.Shared._Crescent.Factions;
using Content.Shared._Crescent.Territory;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Crescent.Territory;

[GenerateTypedNameReferences]
public sealed partial class TerritoryRecruitmentWindow : FancyWindow
{
    public event Action<TerritoryRecruitKind, int, PaymentSource>? OnRecruit;

    private PaymentSource _source = PaymentSource.Personal;

    private TerritoryPaymentState? _payment;

    private int _garrisonRoom;
    private int _escortRoom;

    public TerritoryRecruitmentWindow()
    {
        RobustXamlLoader.Load(this);
        HintLabel.SetHint(Loc.GetString("territory-recruit-ui-hint"));

        PersonalButton.OnPressed += _ => PickSource(PaymentSource.Personal);
        FactionButton.OnPressed += _ => PickSource(PaymentSource.Faction);

        GarrisonOneButton.OnPressed += _ => OnRecruit?.Invoke(TerritoryRecruitKind.Garrison, 1, _source);
        GarrisonFillButton.OnPressed += _ => OnRecruit?.Invoke(TerritoryRecruitKind.Garrison, _garrisonRoom, _source);
        EscortOneButton.OnPressed += _ => OnRecruit?.Invoke(TerritoryRecruitKind.Escort, 1, _source);
        EscortFillButton.OnPressed += _ => OnRecruit?.Invoke(TerritoryRecruitKind.Escort, _escortRoom, _source);
    }

    public void UpdateState(TerritoryRecruitmentState state)
    {
        HolderLabel.SetTextIfChanged(state.Owner == null
            ? Loc.GetString("persistent-poi-production-ui-unclaimed")
            : Loc.GetString("persistent-poi-production-ui-holder", ("faction", FactionDisplay.Abbreviation(state.Owner))));
        LevelLabel.SetTextIfChanged(Loc.GetString("persistent-poi-ui-level", ("level", state.Level)));

        UpdatePayment(state.Payment);

        var open = state.Owner != null && state.Powered && _payment != null;

        _garrisonRoom = Math.Max(0, state.GarrisonLimit - state.Garrison);
        GarrisonLabel.SetTextIfChanged(Loc.GetString("territory-recruit-ui-standing",
            ("count", state.Garrison), ("limit", state.GarrisonLimit)));
        SetButtons(GarrisonOneButton, GarrisonFillButton, open, _garrisonRoom, state.GarrisonPrice);

        _escortRoom = Math.Max(0, Math.Min(state.EscortLimit - state.Escorts, state.SquadRoom));
        EscortLabel.SetTextIfChanged(Loc.GetString("territory-recruit-ui-standing",
            ("count", state.Escorts), ("limit", state.EscortLimit)));
        SetButtons(EscortOneButton, EscortFillButton, open, _escortRoom, state.EscortPrice);

        StatusLabel.SetHint(state.Owner == null
            ? Loc.GetString("territory-recruit-ui-unclaimed")
            : !state.Powered
                ? Loc.GetString("territory-recruit-ui-unpowered")
                : state.SquadRoom <= 0
                    ? Loc.GetString("territory-recruit-ui-squad-full")
                    : string.Empty);
    }

    private void SetButtons(Button one, Button fill, bool open, int room, int price)
    {
        one.Text = Loc.GetString("territory-recruit-ui-one", ("price", price));
        one.Disabled = !open || room <= 0 || !CanAfford(price);

        var count = Math.Max(1, room);
        fill.Text = Loc.GetString("territory-recruit-ui-fill", ("count", count), ("price", count * price));
        fill.Disabled = !open || room <= 1 || !CanAfford(count * price);
    }

    private void UpdatePayment(TerritoryPaymentState? payment)
    {
        _payment = payment;
        PaymentPanel.Visible = payment != null;
        if (payment == null)
            return;

        if (_source == PaymentSource.Faction && !payment.HasTreasury && payment.HasPersonal)
            _source = PaymentSource.Personal;
        else if (_source == PaymentSource.Personal && !payment.HasPersonal && payment.HasTreasury)
            _source = PaymentSource.Faction;

        PersonalButton.Text = payment.HasPersonal
            ? Loc.GetString("territory-payment-personal-button", ("balance", payment.PersonalBalance))
            : Loc.GetString("territory-payment-personal-none");
        PersonalButton.Disabled = !payment.HasPersonal;
        PersonalButton.Pressed = _source == PaymentSource.Personal;

        FactionButton.Text = payment.HasTreasury
            ? Loc.GetString("territory-payment-faction-button",
                ("faction", FactionDisplay.Abbreviation(payment.Faction ?? string.Empty)),
                ("allowance", payment.TreasuryAllowance))
            : Loc.GetString("territory-payment-faction-none");
        FactionButton.Disabled = !payment.HasTreasury;
        FactionButton.Pressed = _source == PaymentSource.Faction;

        PaymentNote.SetHint(_source == PaymentSource.Faction && payment.HasTreasury
            ? Loc.GetString("territory-payment-faction-note",
                ("balance", payment.TreasuryBalance),
                ("percent", (int) MathF.Round(payment.TreasuryShare * 100f)))
            : Loc.GetString("territory-payment-personal-note"));
    }

    private void PickSource(PaymentSource source)
    {
        _source = source;
        PersonalButton.Pressed = source == PaymentSource.Personal;
        FactionButton.Pressed = source == PaymentSource.Faction;
    }

    private bool CanAfford(int price)
    {
        return price > 0 && _payment != null && _payment.CanAfford(_source, price);
    }
}
