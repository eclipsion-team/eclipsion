using Content.Client._Crescent.UI;
using Content.Shared._Crescent.Territory;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;
using Robust.Shared.Utility;

namespace Content.Client._Crescent.Territory;

[GenerateTypedNameReferences]
public sealed partial class TerritoryCommandPanel : BoxContainer
{
    public event Action<TerritoryDefenceOrder, bool>? OnDefenceOrder;
    public event Action<string>? OnRename;
    public event Action? OnAbandon;
    public event Action? OnRemoteFire;

    private const float AbandonConfirmSeconds = 5f;

    private readonly OrderRow _auto;
    private readonly OrderRow _zone;
    private readonly OrderRow _turrets;

    private string? _region;
    private string? _shownName;
    private float _abandonArmed;

    public TerritoryCommandPanel()
    {
        RobustXamlLoader.Load(this);
        CommandNote.SetHint(Loc.GetString("territory-console-command-locked"));
        DefenceNote.SetHint(Loc.GetString("territory-console-command-not-loaded"));
        NameHint.SetHint(Loc.GetString("territory-console-command-name-hint"));

        _auto = AddOrder(TerritoryDefenceOrder.AutoDefense, "territory-console-command-auto", "territory-console-command-auto-desc");
        _zone = AddOrder(TerritoryDefenceOrder.ExclusionZone, "territory-console-command-zone", "territory-console-command-zone-desc");
        _turrets = AddOrder(TerritoryDefenceOrder.TurretsArmed, "territory-console-command-turrets-armed", "territory-console-command-turrets-desc");

        RemoteFireButton.OnPressed += _ => OnRemoteFire?.Invoke();

        AbandonDescription.SetMessage(FormattedMessage.FromUnformatted(Loc.GetString("territory-console-command-abandon-desc")));

        RenameButton.OnPressed += _ => OnRename?.Invoke(NameEdit.Text);
        NameEdit.OnTextEntered += args => OnRename?.Invoke(args.Text);
        ResetNameButton.OnPressed += _ =>
        {
            NameEdit.Text = string.Empty;
            OnRename?.Invoke(string.Empty);
        };

        AbandonButton.OnPressed += _ =>
        {
            if (_abandonArmed <= 0f)
            {
                _abandonArmed = AbandonConfirmSeconds;
                AbandonButton.Text = Loc.GetString("territory-console-command-abandon-confirm");
                return;
            }

            DisarmAbandon();
            OnAbandon?.Invoke();
        };
    }

    private OrderRow AddOrder(TerritoryDefenceOrder order, string title, string description)
    {
        var row = new OrderRow(title, description);
        row.Toggled += enabled => OnDefenceOrder?.Invoke(order, enabled);
        OrdersBox.AddChild(row);
        return row;
    }

    public void UpdateState(TerritoryConsoleState state)
    {
        if (state.Selected != _region)
        {
            _region = state.Selected;
            _shownName = null;
            DisarmAbandon();
        }

        var command = state.CanCommand;
        CommandNote.Visible = !command;

        UpdateDefence(state.Defence, command);

        PrefixLabel.Text = state.NamePrefix is { } prefix ? prefix + "-" : string.Empty;

        var name = state.CustomName ?? string.Empty;
        if (name != _shownName && !NameEdit.HasKeyboardFocus())
        {
            NameEdit.Text = name;
            _shownName = name;
        }

        NameEdit.Editable = command;
        RenameButton.Disabled = !command;
        ResetNameButton.Disabled = !command || state.CustomName == null;

        if (!command)
            DisarmAbandon();

        AbandonButton.Disabled = !command;
    }

    private void UpdateDefence(TerritoryDefenceState? defence, bool command)
    {
        DefenceBox.Visible = defence != null;
        DefenceNote.Visible = defence == null;
        if (defence == null)
            return;

        if (defence.FireControl == 0)
        {
            FireControlLabel.SetTextIfChanged(Loc.GetString("territory-console-command-fire-control-none"));
            FireControlLabel.FontColorOverride = ConsolePalette.Bad;
        }
        else
        {
            FireControlLabel.SetTextIfChanged(Loc.GetString("territory-console-command-fire-control",
                ("powered", defence.FireControlPowered),
                ("consoles", defence.FireControl)));
            FireControlLabel.FontColorOverride = defence.FireControlPowered > 0 ? ConsolePalette.Good : ConsolePalette.Bad;
        }

        MannedLabel.Visible = defence.Manned;
        MannedLabel.SetTextIfChanged(Loc.GetString("territory-console-command-manned"));
        MannedLabel.FontColorOverride = ConsolePalette.Override;

        TargetLabel.SetTextIfChanged(defence.Target is { } target
            ? Loc.GetString("territory-console-command-engaging", ("target", target))
            : Loc.GetString("territory-console-command-idle"));
        TargetLabel.FontColorOverride = defence.Target != null ? ConsolePalette.Bad : ConsolePalette.Muted;

        GunsLabel.SetTextIfChanged(defence.GunLimit is { } limit
            ? Loc.GetString("territory-console-command-guns", ("guns", defence.Guns), ("limit", limit))
            : Loc.GetString("territory-console-command-guns-unlimited", ("guns", defence.Guns)));
        GunsLabel.FontColorOverride = defence.GunLimit is { } cap && defence.Guns > cap ? ConsolePalette.Warn : ConsolePalette.Normal;

        TurretsLabel.SetTextIfChanged(Loc.GetString("territory-console-command-turrets", ("turrets", defence.Turrets)));

        RemoteFireButton.Disabled = !command || !defence.RemoteFireAvailable;
        RemoteFireHint.SetTextIfChanged(Loc.GetString(defence.RemoteFireAvailable
            ? "territory-console-command-remote-fire-hint"
            : "territory-console-command-remote-fire-unavailable"));

        _auto.Update(defence.AutoDefense);
        _zone.Update(defence.ExclusionZone);
        _turrets.Update(defence.TurretsArmed);

        _auto.Disabled = !command;
        _turrets.Disabled = !command;

        _zone.Disabled = !command || !defence.AutoDefense;
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (_abandonArmed <= 0f)
            return;

        _abandonArmed -= args.DeltaSeconds;
        if (_abandonArmed <= 0f)
            DisarmAbandon();
    }

    private void DisarmAbandon()
    {
        _abandonArmed = 0f;
        AbandonButton.Text = Loc.GetString("territory-console-command-abandon");
    }

    private sealed class OrderRow : BoxContainer
    {
        public event Action<bool>? Toggled;

        private readonly Button _switch;
        private readonly Label _title;

        public OrderRow(string title, string description)
        {
            Orientation = LayoutOrientation.Horizontal;
            SeparationOverride = 8;

            _switch = new Button { MinWidth = 64, ToggleMode = true, VerticalAlignment = VAlignment.Center };
            _switch.OnToggled += args => Toggled?.Invoke(args.Pressed);

            _title = new Label { Text = Loc.GetString(title), ClipText = true };
            var text = new BoxContainer { Orientation = LayoutOrientation.Vertical, HorizontalExpand = true };
            text.AddChild(_title);
            var descriptionLabel = new RichTextLabel { HorizontalExpand = true };
            descriptionLabel.SetHint(Loc.GetString(description));
            text.AddChild(descriptionLabel);

            AddChild(_switch);
            AddChild(text);
        }

        public bool Disabled
        {
            set => _switch.Disabled = value;
        }

        public void Update(bool enabled)
        {
            _switch.Pressed = enabled;
            _switch.Text = Loc.GetString(enabled ? "territory-console-command-on" : "territory-console-command-off");
            _switch.Label.FontColorOverride = enabled ? ConsolePalette.Good : ConsolePalette.Muted;
        }
    }
}
