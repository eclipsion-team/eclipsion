[GenerateTypedNameReferences]
public sealed partial class TerritoryDroneBayWindow : FancyWindow
{
    public event Action<string, PaymentSource>? OnLaunch;

    public event Action<NetEntity?, TerritoryDroneCommand, NetEntity?>? OnCommand;

    private PaymentSource _source = PaymentSource.Personal;

    private TerritoryPaymentState? _payment;

    private bool _canOrder;

    private NetEntity? _selectedTarget;

    // so an empty first state still shows the placeholder
    private bool _dronesBuilt;
    private bool _targetsBuilt;
    private bool _hullsBuilt;

    private readonly List<(string Id, Label Price, Button Button)> _hullRows = new();
    private readonly List<(NetEntity Id, ContainerButton Row, Label Name, Label Faction, Label Distance)> _targetRows = new();
    private readonly List<(NetEntity Id, DroneCard Card)> _cards = new();

    public TerritoryDroneBayWindow()
    {
        RobustXamlLoader.Load(this);

        Tabs.SetTabTitle(0, Loc.GetString("territory-drone-bay-ui-tab-squadron"));
        Tabs.SetTabTitle(1, Loc.GetString("territory-drone-bay-ui-tab-hangar"));
        SetMarkup(HintLabel, Loc.GetString("territory-drone-bay-ui-hint"));

        PersonalButton.OnPressed += _ => PickSource(PaymentSource.Personal);
        FactionButton.OnPressed += _ => PickSource(PaymentSource.Faction);

        AllDefendButton.OnPressed += _ => OnCommand?.Invoke(null, TerritoryDroneCommand.Defend, null);
        AllAttackButton.OnPressed += _ =>
        {
            if (_selectedTarget is { } target)
                OnCommand?.Invoke(null, TerritoryDroneCommand.Attack, target);
        };
        AllHoldButton.OnPressed += _ => OnCommand?.Invoke(null, TerritoryDroneCommand.Hold, null);
        AllPowerDownButton.OnPressed += _ => OnCommand?.Invoke(null, TerritoryDroneCommand.PowerDown, null);
        AllPowerUpButton.OnPressed += _ => OnCommand?.Invoke(null, TerritoryDroneCommand.PowerUp, null);

        AllDefendButton.ToolTip = Loc.GetString("territory-drone-bay-ui-defend-tip");
        AllHoldButton.ToolTip = Loc.GetString("territory-drone-bay-ui-hold-tip");
        AllPowerDownButton.ToolTip = Loc.GetString("territory-drone-bay-ui-power-down-tip");
        AllPowerUpButton.ToolTip = Loc.GetString("territory-drone-bay-ui-power-up-tip");
    }

    public void UpdateState(TerritoryDroneBayState state)
    {
        HolderLabel.SetTextIfChanged(state.Owner == null
            ? Loc.GetString("persistent-poi-production-ui-unclaimed")
            : Loc.GetString("persistent-poi-production-ui-holder", ("faction", FactionDisplay.Abbreviation(state.Owner))));
        LevelLabel.SetTextIfChanged(Loc.GetString("persistent-poi-ui-level", ("level", state.Level)));

        var problem = state.Owner == null
            ? Loc.GetString("territory-drone-bay-ui-unclaimed")
            : !state.Powered
                ? Loc.GetString("territory-drone-bay-ui-unpowered")
                : state.OldPickets
                    ? Loc.GetString("territory-drone-bay-ui-old-pickets")
                    : state.NoRank
                        ? Loc.GetString("territory-drone-bay-ui-no-rank")
                        : !state.CanCommand
                            ? Loc.GetString("territory-drone-bay-ui-not-holder")
                            : null;

        StatusLabel.Visible = problem != null;
        if (problem != null)
            SetMarkup(StatusLabel, problem);

        _canOrder = problem == null;

        UpdateTargets(state);
        UpdateSquadron(state);
        UpdateHangar(state);
    }

    #region Squadron

    private void UpdateSquadron(TerritoryDroneBayState state)
    {
        SquadronSummary.SetTextIfChanged(Loc.GetString("territory-drone-bay-ui-summary",
            ("count", state.Drones.Count), ("bought", state.Bought), ("limit", state.Limit)));
        DronesHeading.SetTextIfChanged(Loc.GetString("territory-drone-bay-ui-drones-heading"));

        var noDrones = state.Drones.Count == 0;
        var reason = !_canOrder
            ? Loc.GetString("territory-drone-bay-ui-cannot-order")
            : noDrones
                ? Loc.GetString("territory-drone-bay-ui-no-drones-tip")
                : null;

        AllDefendButton.SetDisabled(reason != null, reason);
        AllHoldButton.SetDisabled(reason != null, reason);
        AllPowerDownButton.SetDisabled(reason != null, reason);
        AllPowerUpButton.SetDisabled(reason != null, reason);

        var attackReason = reason ?? (_selectedTarget == null ? Loc.GetString("territory-drone-bay-ui-pick-target-tip") : null);
        AllAttackButton.SetDisabled(attackReason != null, attackReason);
        if (attackReason == null)
            AllAttackButton.ToolTip = Loc.GetString("territory-drone-bay-ui-attack-tip");

        // only rebuild when the drones change, otherwise the refresh eats clicks
        if (!_dronesBuilt || !_cards.Select(c => c.Id).SequenceEqual(state.Drones.Select(d => d.Drone)))
        {
            _dronesBuilt = true;
            DroneList.RemoveAllChildren();
            _cards.Clear();

            if (noDrones)
            {
                var empty = new RichTextLabel { HorizontalExpand = true, Margin = new Thickness(4) };
                SetMarkup(empty, Loc.GetString("territory-drone-bay-ui-no-drones"));
                DroneList.AddChild(empty);
            }

            foreach (var entry in state.Drones)
            {
                var card = new DroneCard(this, entry.Drone);
                DroneList.AddChild(card);
                _cards.Add((entry.Drone, card));
            }
        }

        for (var i = 0; i < state.Drones.Count; i++)
        {
            _cards[i].Card.Update(state.Drones[i], _canOrder, _selectedTarget != null);
        }
    }

    private void UpdateTargets(TerritoryDroneBayState state)
    {
        TargetsHeading.SetTextIfChanged(Loc.GetString("territory-drone-bay-ui-targets-heading",
            ("range", state.AttackRange)));

        if (_selectedTarget is { } selected && state.Targets.All(t => t.Target != selected))
            _selectedTarget = null;

        if (!_targetsBuilt || !_targetRows.Select(r => r.Id).SequenceEqual(state.Targets.Select(t => t.Target)))
        {
            _targetsBuilt = true;
            TargetList.RemoveAllChildren();
            _targetRows.Clear();

            if (state.Targets.Count == 0)
            {
                TargetList.AddChild(new Label
                {
                    Text = Loc.GetString("territory-drone-bay-ui-no-targets", ("range", state.AttackRange)),
                    StyleClasses = { "LabelSecondaryColor" },
                    Margin = new Thickness(4, 2),
                });
            }

            foreach (var target in state.Targets)
            {
                var id = target.Target;
                var row = new ContainerButton
                {
                    ToggleMode = true,
                    MinHeight = 28,
                    HorizontalExpand = true,
                    StyleClasses = { ContainerButton.StyleClassButton },
                };

                var line = new BoxContainer
                {
                    Orientation = BoxContainer.LayoutOrientation.Horizontal,
                    SeparationOverride = 8,
                    Margin = new Thickness(6, 2),
                };

                var name = new Label { HorizontalExpand = true, ClipText = true, VerticalAlignment = VAlignment.Center };
                var faction = new Label
                {
                    MinWidth = 80,
                    VerticalAlignment = VAlignment.Center,
                    StyleClasses = { "LabelSecondaryColor" },
                };
                var distance = new Label
                {
                    MinWidth = 80,
                    Align = Label.AlignMode.Right,
                    VerticalAlignment = VAlignment.Center,
                };

                line.AddChild(name);
                line.AddChild(faction);
                line.AddChild(distance);
                row.AddChild(line);

                row.OnPressed += _ =>
                {
                    _selectedTarget = row.Pressed ? id : null;
                    RefreshSelection();
                };

                TargetList.AddChild(row);
                _targetRows.Add((id, row, name, faction, distance));
            }
        }

        for (var i = 0; i < state.Targets.Count; i++)
        {
            var target = state.Targets[i];
            var row = _targetRows[i];
            row.Name.SetTextIfChanged(target.Name);
            row.Row.ToolTip = target.Name;
            row.Faction.SetTextIfChanged(target.Faction == null
                ? Loc.GetString("territory-drone-bay-ui-no-faction")
                : FactionDisplay.Abbreviation(target.Faction));
            row.Distance.SetTextIfChanged(Loc.GetString("territory-drone-bay-ui-metres", ("distance", target.Distance)));
        }

        RefreshSelection();
    }

    private void RefreshSelection()
    {
        string? selectedName = null;
        foreach (var row in _targetRows)
        {
            row.Row.Pressed = row.Id == _selectedTarget;
            if (row.Id == _selectedTarget)
                selectedName = row.Name.Text;
        }

        SetMarkup(TargetNote, selectedName == null
            ? Loc.GetString("territory-drone-bay-ui-target-none")
            : Loc.GetString("territory-drone-bay-ui-target-selected", ("target", FormattedMessage.EscapeText(selectedName))));

        if (!_canOrder || _cards.Count == 0)
            return;

        var reason = _selectedTarget == null ? Loc.GetString("territory-drone-bay-ui-pick-target-tip") : null;
        AllAttackButton.SetDisabled(reason != null, reason);
        if (reason == null)
            AllAttackButton.ToolTip = Loc.GetString("territory-drone-bay-ui-attack-tip");

        foreach (var (_, card) in _cards)
        {
            card.SetCanAttack(_selectedTarget != null);
        }
    }

    private void Command(NetEntity drone, TerritoryDroneCommand command)
    {
        if (command == TerritoryDroneCommand.Attack)
        {
            if (_selectedTarget is { } target)
                OnCommand?.Invoke(drone, command, target);

            return;
        }

        OnCommand?.Invoke(drone, command, null);
    }

    #endregion

    #region Hangar

    private void UpdateHangar(TerritoryDroneBayState state)
    {
        UpdatePayment(state.Payment);

        BoughtLabel.SetTextIfChanged(Loc.GetString("territory-drone-bay-ui-flying",
            ("count", state.Bought), ("limit", state.Limit)));

        var full = state.Limit > 0 && state.Bought >= state.Limit;
        var open = _canOrder && _payment != null && state.Limit > 0 && !full;

        if (!_hullsBuilt || !_hullRows.Select(r => r.Id).SequenceEqual(state.Hulls.Select(h => h.Id)))
        {
            _hullsBuilt = true;
            HullList.RemoveAllChildren();
            _hullRows.Clear();
            foreach (var hull in state.Hulls)
            {
                var row = new BoxContainer
                {
                    Orientation = BoxContainer.LayoutOrientation.Horizontal,
                    SeparationOverride = 8,
                    MinHeight = 30,
                };
                row.AddChild(new Label
                {
                    Text = hull.Name,
                    HorizontalExpand = true,
                    VerticalAlignment = VAlignment.Center,
                });

                var price = new Label
                {
                    MinWidth = 110,
                    Align = Label.AlignMode.Right,
                    VerticalAlignment = VAlignment.Center,
                    StyleClasses = { "LabelSecondaryColor" },
                };
                row.AddChild(price);

                var id = hull.Id;
                var buy = new Button
                {
                    MinWidth = 120,
                    Text = Loc.GetString("territory-drone-bay-ui-buy"),
                };
                buy.OnPressed += _ => OnLaunch?.Invoke(id, _source);
                row.AddChild(buy);

                HullList.AddChild(row);
                _hullRows.Add((id, price, buy));
            }
        }

        for (var i = 0; i < state.Hulls.Count; i++)
        {
            var hull = state.Hulls[i];
            var (_, price, buy) = _hullRows[i];
            price.SetTextIfChanged(Loc.GetString("territory-drone-bay-ui-price", ("price", hull.Price)));

            string? reason = null;
            if (!open)
                reason = Loc.GetString("territory-drone-bay-ui-cannot-buy");
            else if (!CanAfford(hull.Price))
                reason = Loc.GetString("territory-drone-bay-ui-cannot-afford");

            buy.SetDisabled(reason != null, reason);
        }

        SetMarkup(HangarStatus, state.Owner == null
            ? string.Empty
            : state.Limit <= 0
                ? Loc.GetString("territory-drone-bay-ui-level")
                : full
                    ? Loc.GetString("territory-drone-bay-ui-full")
                    : string.Empty);
    }

    private void UpdatePayment(TerritoryPaymentState? payment)
    {
        _payment = payment;
        PaymentPanel.Visible = payment != null;
        if (payment == null)
            return;

        if (_source == PaymentSource.Faction && !payment.HasTreasury && payment.HasPersonal)
            _source = PaymentSource.Personal;
        else if (_source == PaymentSource.Personal && !payment.HasPersonal && payment.HasTreasury)
            _source = PaymentSource.Faction;

        PersonalButton.Text = payment.HasPersonal
            ? Loc.GetString("territory-payment-personal-button", ("balance", payment.PersonalBalance))
            : Loc.GetString("territory-payment-personal-none");
        PersonalButton.Disabled = !payment.HasPersonal;
        PersonalButton.Pressed = _source == PaymentSource.Personal;

        FactionButton.Text = payment.HasTreasury
            ? Loc.GetString("territory-payment-faction-button",
                ("faction", FactionDisplay.Abbreviation(payment.Faction ?? string.Empty)),
                ("allowance", payment.TreasuryAllowance))
            : Loc.GetString("territory-payment-faction-none");
        FactionButton.Disabled = !payment.HasTreasury;
        FactionButton.Pressed = _source == PaymentSource.Faction;

        PaymentNote.SetHint(_source == PaymentSource.Faction && payment.HasTreasury
            ? Loc.GetString("territory-payment-faction-note",
                ("balance", payment.TreasuryBalance),
                ("percent", (int) MathF.Round(payment.TreasuryShare * 100f)))
            : Loc.GetString("territory-payment-personal-note"));
    }

    private void PickSource(PaymentSource source)
    {
        _source = source;
        PersonalButton.Pressed = source == PaymentSource.Personal;
        FactionButton.Pressed = source == PaymentSource.Faction;
    }

    private bool CanAfford(int price)
    {
        return price > 0 && _payment != null && _payment.CanAfford(_source, price);
    }

    #endregion

    // SetHint escapes markup
    private static void SetMarkup(RichTextLabel label, string markup)
    {
        var message = FormattedMessage.FromMarkupPermissive(markup);
        if (label.GetMessage() == message.ToMarkup())
            return;

        label.SetMessage(message, defaultColor: ConsolePalette.Secondary);
    }

    private static Color OrderColor(TerritoryDroneOrder order)
    {
        return order switch
        {
            TerritoryDroneOrder.Defend => ConsolePalette.Good,
            TerritoryDroneOrder.Attack => ConsolePalette.Bad,
            TerritoryDroneOrder.Hold => ConsolePalette.Warn,
            _ => ConsolePalette.Muted,
        };
    }

    private sealed class DroneCard : PanelContainer
    {
        private readonly StyleBoxFlat _box;
        private readonly Label _name;
        private readonly Label _order;
        private readonly RichTextLabel _info;
        private readonly RichTextLabel _activity;
        private readonly Button _defend;
        private readonly Button _attack;
        private readonly Button _hold;
        private readonly Button _power;
        private readonly ConfirmButton _scuttle;

        private bool _canOrder;
        private TerritoryDroneOrder _current;

        public DroneCard(TerritoryDroneBayWindow window, NetEntity drone)
        {
            HorizontalExpand = true;
            _box = new StyleBoxFlat
            {
                BackgroundColor = Color.FromHex("#1b1b1e"),
                BorderColor = Color.FromHex("#3a3a44"),
                BorderThickness = new Thickness(1, 1, 1, 1),
                ContentMarginLeftOverride = 8,
                ContentMarginRightOverride = 8,
                ContentMarginTopOverride = 6,
                ContentMarginBottomOverride = 6,
            };
            PanelOverride = _box;

            var body = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Vertical,
                SeparationOverride = 4,
                HorizontalExpand = true,
            };

            var top = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                SeparationOverride = 8,
            };
            _name = new Label { HorizontalExpand = true, ClipText = true, StyleClasses = { "LabelHeading" } };
            _order = new Label { VerticalAlignment = VAlignment.Center };
            top.AddChild(_name);
            top.AddChild(_order);
            body.AddChild(top);

            _info = new RichTextLabel { HorizontalExpand = true };
            _activity = new RichTextLabel { HorizontalExpand = true };
            body.AddChild(_info);
            body.AddChild(_activity);

            var buttons = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                SeparationOverride = 2,
                Margin = new Thickness(0, 2, 0, 0),
            };

            _defend = OrderButton("territory-drone-bay-ui-defend", "OpenRight", true);
            _attack = OrderButton("territory-drone-bay-ui-attack", "OpenBoth", true);
            _hold = OrderButton("territory-drone-bay-ui-hold", "OpenBoth", true);
            _power = OrderButton("territory-drone-bay-ui-power-down", "OpenBoth", false);
            _scuttle = new ConfirmButton
            {
                Text = Loc.GetString("territory-drone-bay-ui-scuttle"),
                ConfirmationText = Loc.GetString("territory-drone-bay-ui-scuttle-confirm"),
                ResetTime = TimeSpan.FromSeconds(3),
                HorizontalExpand = true,
                MinHeight = 28,
                StyleClasses = { "OpenLeft", "Caution" },
                ToolTip = Loc.GetString("territory-drone-bay-ui-scuttle-tip"),
            };

            _defend.ToolTip = Loc.GetString("territory-drone-bay-ui-defend-tip");
            _hold.ToolTip = Loc.GetString("territory-drone-bay-ui-hold-tip");

            _defend.OnPressed += _ => Pick(TerritoryDroneOrder.Defend, () => window.Command(drone, TerritoryDroneCommand.Defend));
            _attack.OnPressed += _ => Pick(TerritoryDroneOrder.Attack, () => window.Command(drone, TerritoryDroneCommand.Attack));
            _hold.OnPressed += _ => Pick(TerritoryDroneOrder.Hold, () => window.Command(drone, TerritoryDroneCommand.Hold));
            _power.OnPressed += _ => window.Command(drone, _current == TerritoryDroneOrder.Offline
                ? TerritoryDroneCommand.PowerUp
                : TerritoryDroneCommand.PowerDown);
            _scuttle.OnPressed += _ => window.Command(drone, TerritoryDroneCommand.Scuttle);

            buttons.AddChild(_defend);
            buttons.AddChild(_attack);
            buttons.AddChild(_hold);
            buttons.AddChild(_power);
            buttons.AddChild(_scuttle);
            body.AddChild(buttons);

            AddChild(body);
        }

        private static Button OrderButton(string text, string style, bool toggle)
        {
            return new Button
            {
                Text = Loc.GetString(text),
                ToggleMode = toggle,
                HorizontalExpand = true,
                MinHeight = 28,
                StyleClasses = { style },
            };
        }

        private void Pick(TerritoryDroneOrder order, Action send)
        {
            send();
            ShowOrder(order);
        }

        private void ShowOrder(TerritoryDroneOrder order)
        {
            _defend.Pressed = order == TerritoryDroneOrder.Defend;
            _attack.Pressed = order == TerritoryDroneOrder.Attack;
            _hold.Pressed = order == TerritoryDroneOrder.Hold;
        }

        public void Update(TerritoryDroneEntry entry, bool canOrder, bool hasTarget)
        {
            _canOrder = canOrder;
            _current = entry.Order;

            _name.SetTextIfChanged(entry.Name);
            _name.ToolTip = entry.Name;

            var color = OrderColor(entry.Order);
            _order.SetTextIfChanged(Loc.GetString(entry.Order switch
            {
                TerritoryDroneOrder.Defend => "territory-drone-bay-ui-order-defend",
                TerritoryDroneOrder.Attack => "territory-drone-bay-ui-order-attack",
                TerritoryDroneOrder.Hold => "territory-drone-bay-ui-order-hold",
                _ => "territory-drone-bay-ui-order-offline",
            }));
            _order.FontColorOverride = color;
            _box.BorderColor = color.WithAlpha(0.6f);

            var integrityColor = entry.Integrity >= 70
                ? ConsolePalette.Good
                : entry.Integrity >= 35
                    ? ConsolePalette.Warn
                    : ConsolePalette.Bad;
            SetMarkup(_info, Loc.GetString("territory-drone-bay-ui-drone-info",
                ("origin", Loc.GetString(entry.Bought
                    ? "territory-drone-bay-ui-origin-bought"
                    : "territory-drone-bay-ui-origin-garrison")),
                ("distance", entry.Distance),
                ("integrity", entry.Integrity),
                ("color", integrityColor.ToHex())));

            var target = FormattedMessage.EscapeText(entry.Target ?? string.Empty);
            SetMarkup(_activity, entry.Unpowered
                ? Loc.GetString("territory-drone-bay-ui-activity-unpowered")
                : entry.Order switch
                {
                    TerritoryDroneOrder.Offline => Loc.GetString("territory-drone-bay-ui-activity-offline"),
                    TerritoryDroneOrder.Hold => Loc.GetString("territory-drone-bay-ui-activity-hold"),
                    TerritoryDroneOrder.Attack => Loc.GetString("territory-drone-bay-ui-activity-attack", ("target", target)),
                    _ when entry.Returning => Loc.GetString("territory-drone-bay-ui-activity-returning"),
                    _ when entry.Engaging => Loc.GetString("territory-drone-bay-ui-activity-engaging", ("target", target)),
                    _ => Loc.GetString("territory-drone-bay-ui-activity-patrol"),
                });

            ShowOrder(entry.Order);

            var offline = entry.Order == TerritoryDroneOrder.Offline;
            _power.Text = Loc.GetString(offline ? "territory-drone-bay-ui-power-up" : "territory-drone-bay-ui-power-down");
            _power.ToolTip = Loc.GetString(offline
                ? "territory-drone-bay-ui-power-up-tip"
                : "territory-drone-bay-ui-power-down-tip");

            var reason = canOrder ? null : Loc.GetString("territory-drone-bay-ui-cannot-order");
            _defend.SetDisabled(reason != null, reason);
            _hold.SetDisabled(reason != null, reason);
            _power.SetDisabled(reason != null, reason);
            if (reason == null)
            {
                _defend.ToolTip = Loc.GetString("territory-drone-bay-ui-defend-tip");
                _hold.ToolTip = Loc.GetString("territory-drone-bay-ui-hold-tip");
                _power.ToolTip = Loc.GetString(offline
                    ? "territory-drone-bay-ui-power-up-tip"
                    : "territory-drone-bay-ui-power-down-tip");
            }

            // confirm button disables itself between clicks
            if (!_scuttle.IsConfirming)
            {
                _scuttle.Disabled = !canOrder;
                _scuttle.ToolTip = canOrder
                    ? Loc.GetString("territory-drone-bay-ui-scuttle-tip")
                    : Loc.GetString("territory-drone-bay-ui-cannot-order");
            }

            SetCanAttack(hasTarget);
        }

        public void SetCanAttack(bool hasTarget)
        {
            var reason = !_canOrder
                ? Loc.GetString("territory-drone-bay-ui-cannot-order")
                : !hasTarget
                    ? Loc.GetString("territory-drone-bay-ui-pick-target-tip")
                    : null;

            _attack.SetDisabled(reason != null, reason);
            if (reason == null)
                _attack.ToolTip = Loc.GetString("territory-drone-bay-ui-attack-tip");
        }
    }
