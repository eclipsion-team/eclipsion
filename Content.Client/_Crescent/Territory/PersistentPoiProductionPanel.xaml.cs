[GenerateTypedNameReferences]
public sealed partial class PersistentPoiProductionPanel : BoxContainer
{
    public event Action<NetEntity>? OnToggle;

    public event Action<NetEntity, string>? OnSelectRecipe;

    public event Action<NetEntity>? OnDispense;

    public event Action<NetEntity>? OnDecommission;

    public event Action<string>? OnSetCapability;

    public event Action<NetEntity, PaymentSource>? OnRush;

    public event Action<PaymentSource>? OnOvertime;

    private PaymentSource _source = PaymentSource.Personal;

    private TerritoryPaymentState? _payment;

    private readonly Dictionary<NetEntity, MachineRow> _rows = new();

    private List<PersistentPoiCapabilityOption> _capabilities = new();
    private string? _currentCapability;

    private string? _pendingCapability;

    private bool _updatingCapabilities;

    private bool _remote;

    public bool Remote
    {
        get => _remote;
        set
        {
            _remote = value;
            HintLabel.SetHint(Loc.GetString(value
                ? "persistent-poi-production-ui-remote-hint"
                : "persistent-poi-production-ui-hint"));

            foreach (var row in _rows.Values)
            {
                row.SetRemote(value);
            }
        }
    }

    private bool _locked;

    public bool Locked
    {
        get => _locked;
        set
        {
            if (_locked == value)
                return;

            _locked = value;
            CapabilitySelector.Disabled = value;
            RefreshCapabilityControls();

            foreach (var row in _rows.Values)
            {
                row.SetLocked(value);
            }
        }
    }

    public PersistentPoiProductionPanel()
    {
        RobustXamlLoader.Load(this);
        HintLabel.SetHint(Loc.GetString("persistent-poi-production-ui-hint"));
        EmptyLabel.SetHint(Loc.GetString("persistent-poi-production-ui-empty"));

        CapabilitySelector.OnItemSelected += args =>
        {
            if (_updatingCapabilities || args.Id < 0 || args.Id >= _capabilities.Count)
                return;

            CapabilitySelector.SelectId(args.Id);
            _pendingCapability = _capabilities[args.Id].Id;
            RefreshCapabilityControls();
        };

        RetoolButton.OnPressed += _ =>
        {
            if (_pendingCapability != null && _pendingCapability != _currentCapability)
                OnSetCapability?.Invoke(_pendingCapability);
        };

        PersonalButton.OnPressed += _ => PickSource(PaymentSource.Personal);
        FactionButton.OnPressed += _ => PickSource(PaymentSource.Faction);
        OvertimeButton.OnPressed += _ => OnOvertime?.Invoke(_source);
    }

    public void UpdateState(PersistentPoiProductionConsoleState state)
    {
        HolderLabel.SetTextIfChanged(state.Owner == null
            ? Loc.GetString("persistent-poi-production-ui-unclaimed")
            : Loc.GetString("persistent-poi-production-ui-holder", ("faction", FactionDisplay.Abbreviation(state.Owner))));
        LevelLabel.SetTextIfChanged(Loc.GetString("persistent-poi-ui-level", ("level", state.Level)));

        UpdateCapabilities(state);
        UpdatePayment(state);

        FactoriesLabel.SetTextIfChanged(state.FactoryLimit is { } limit
            ? Loc.GetString("persistent-poi-production-ui-factories", ("count", state.Factories), ("limit", limit))
            : Loc.GetString("persistent-poi-production-ui-factories-unlimited", ("count", state.Factories)));
        FactoriesLabel.FontColorOverride = state.FactoryLimit is { } cap && state.Factories > cap
            ? ConsolePalette.Warn
            : ConsolePalette.Normal;

        CountLabel.SetTextIfChanged(Loc.GetString("persistent-poi-production-ui-count", ("count", state.Machines.Count)));
        EmptyLabel.Visible = state.Machines.Count == 0;

        var seen = new HashSet<NetEntity>();
        for (var i = 0; i < state.Machines.Count; i++)
        {
            var machine = state.Machines[i];
            seen.Add(machine.Machine);

            if (!_rows.TryGetValue(machine.Machine, out var row))
            {
                row = new MachineRow(machine.Machine);
                row.OnToggle += uid => OnToggle?.Invoke(uid);
                row.OnSelectRecipe += (uid, recipe) => OnSelectRecipe?.Invoke(uid, recipe);
                row.OnDispense += uid => OnDispense?.Invoke(uid);
                row.OnDecommission += uid => OnDecommission?.Invoke(uid);
                row.OnRush += uid => OnRush?.Invoke(uid, _source);
                row.SetRemote(_remote);
                row.SetLocked(_locked);
                _rows[machine.Machine] = row;
                MachinesContainer.AddChild(row);
            }

            row.Update(machine);
            row.SetRush(machine.RushPrice, CanAfford(machine.RushPrice));
            row.SetPositionInParent(i);
        }

        foreach (var (machine, row) in _rows.ToArray())
        {
            if (seen.Contains(machine))
                continue;

            MachinesContainer.RemoveChild(row);
            _rows.Remove(machine);
        }
    }

    private void UpdatePayment(PersistentPoiProductionConsoleState state)
    {
        _payment = state.Payment;
        PaymentPanel.Visible = _payment != null;
        if (_payment is not { } payment)
            return;

        if (_source == PaymentSource.Faction && !payment.HasTreasury && payment.HasPersonal)
            _source = PaymentSource.Personal;
        else if (_source == PaymentSource.Personal && !payment.HasPersonal && payment.HasTreasury)
            _source = PaymentSource.Faction;

        PersonalButton.Text = payment.HasPersonal
            ? Loc.GetString("territory-payment-personal-button", ("balance", payment.PersonalBalance))
            : Loc.GetString("territory-payment-personal-none");
        PersonalButton.Disabled = !payment.HasPersonal;
        PersonalButton.Pressed = _source == PaymentSource.Personal;

        FactionButton.Text = payment.HasTreasury
            ? Loc.GetString("territory-payment-faction-button",
                ("faction", FactionDisplay.Abbreviation(payment.Faction ?? string.Empty)),
                ("allowance", payment.TreasuryAllowance))
            : Loc.GetString("territory-payment-faction-none");
        FactionButton.Disabled = !payment.HasTreasury;
        FactionButton.Pressed = _source == PaymentSource.Faction;

        PaymentNote.SetHint(_source == PaymentSource.Faction && payment.HasTreasury
            ? Loc.GetString("territory-payment-faction-note",
                ("balance", payment.TreasuryBalance),
                ("percent", (int) MathF.Round(payment.TreasuryShare * 100f)))
            : Loc.GetString("territory-payment-personal-note"));

        if (state.OvertimeSeconds > 0f)
        {
            var left = TimeSpan.FromSeconds(state.OvertimeSeconds);
            OvertimeLabel.SetTextIfChanged(Loc.GetString("persistent-poi-overtime-active",
                ("speed", state.OvertimeSpeed),
                ("time", $"{(int) left.TotalMinutes}:{left.Seconds:00}")));
            OvertimeLabel.FontColorOverride = ConsolePalette.Good;
        }
        else
        {
            OvertimeLabel.SetTextIfChanged(Loc.GetString("persistent-poi-overtime-off", ("speed", state.OvertimeSpeed)));
            OvertimeLabel.FontColorOverride = ConsolePalette.Muted;
        }

        if (state.OvertimeMaxed)
        {
            OvertimeButton.Text = Loc.GetString("persistent-poi-overtime-button-maxed");
            OvertimeButton.Disabled = true;
        }
        else
        {
            OvertimeButton.Text = state.OvertimePrice > 0
                ? Loc.GetString("persistent-poi-overtime-button", ("minutes", state.OvertimeMinutes), ("price", state.OvertimePrice))
                : Loc.GetString("persistent-poi-overtime-button-idle", ("minutes", state.OvertimeMinutes));
            OvertimeButton.Disabled = _locked || state.OvertimePrice <= 0 || !CanAfford(state.OvertimePrice);
        }
    }

    private void PickSource(PaymentSource source)
    {
        _source = source;
        PersonalButton.Pressed = source == PaymentSource.Personal;
        FactionButton.Pressed = source == PaymentSource.Faction;
    }

    private bool CanAfford(int price)
    {
        return !_locked && price > 0 && _payment != null && _payment.CanAfford(_source, price);
    }

    private void UpdateCapabilities(PersistentPoiProductionConsoleState state)
    {
        _updatingCapabilities = true;

        if (!_capabilities.Select(c => c.Id).SequenceEqual(state.Capabilities.Select(c => c.Id)))
        {
            CapabilitySelector.Clear();
            for (var i = 0; i < state.Capabilities.Count; i++)
            {
                CapabilitySelector.AddItem(state.Capabilities[i].Name, i);
            }

            _capabilities = state.Capabilities;
        }

        if (_pendingCapability != null && _pendingCapability == state.Capability)
            _pendingCapability = null;

        _currentCapability = state.Capability;

        var shown = _pendingCapability ?? _currentCapability;
        var index = _capabilities.FindIndex(c => c.Id == shown);
        if (index >= 0 && CapabilitySelector.SelectedId != index)
            CapabilitySelector.SelectId(index);

        _updatingCapabilities = false;
        RefreshCapabilityControls();
    }

    private void RefreshCapabilityControls()
    {
        var shown = _pendingCapability ?? _currentCapability;
        var option = _capabilities.FirstOrDefault(c => c.Id == shown);

        CapabilityDescription.SetHint(option == null
            ? Loc.GetString("persistent-poi-production-ui-no-capability")
            : option.Description);

        RetoolButton.Disabled = _locked || _pendingCapability == null || _pendingCapability == _currentCapability;
        RetoolButton.Text = _currentCapability == null
            ? Loc.GetString("persistent-poi-production-ui-tool")
            : Loc.GetString("persistent-poi-production-ui-retool");
    }

    private sealed class MachineRow : PanelContainer
    {
        public event Action<NetEntity>? OnToggle;

        public event Action<NetEntity, string>? OnSelectRecipe;

        public event Action<NetEntity>? OnDispense;

        public event Action<NetEntity>? OnDecommission;

        public event Action<NetEntity>? OnRush;

        private readonly NetEntity _machine;
        private readonly Label _name;
        private readonly Label _status;
        private readonly OptionButton _recipes;
        private readonly Label _output;
        private readonly ProgressBar _progress;
        private readonly StyleBoxFlat _progressFill = new();
        private readonly Label _stored;
        private readonly Button _toggle;
        private readonly Button _dispense;
        private readonly Button _decommission;
        private readonly Button _rush;

        private List<string> _recipeIds = new();

        private bool _updating;

        private bool _decommissionArmed;

        private bool _remote;

        private bool _locked;

        public MachineRow(NetEntity machine)
        {
            _machine = machine;

            PanelOverride = new StyleBoxFlat
            {
                BackgroundColor = Color.FromHex("#1b1b1e"),
                BorderColor = Color.FromHex("#3c3c45"),
                BorderThickness = new Thickness(1),
                ContentMarginLeftOverride = 6,
                ContentMarginRightOverride = 6,
                ContentMarginTopOverride = 4,
                ContentMarginBottomOverride = 4,
            };

            var lines = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, SeparationOverride = 4 };
            AddChild(lines);

            // name and what it is doing right now
            var header = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 8 };
            _name = new Label { StyleClasses = { StyleNano.StyleClassLabelKeyText }, HorizontalExpand = true, ClipText = true };
            _status = new Label();
            header.AddChild(_name);
            header.AddChild(_status);
            lines.AddChild(header);

            // what it makes
            var recipeLine = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 8 };
            _recipes = new OptionButton { MinWidth = 200 };
            _recipes.OnItemSelected += OnRecipePicked;
            _output = new Label { HorizontalExpand = true, ClipText = true, StyleClasses = { StyleBase.StyleClassLabelSubText } };
            recipeLine.AddChild(_recipes);
            recipeLine.AddChild(_output);
            lines.AddChild(recipeLine);

            var progressLine = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 8 };
            _progress = new ProgressBar
            {
                MinValue = 0f,
                MaxValue = 1f,
                HorizontalExpand = true,
                SetHeight = 8,
                VerticalAlignment = VAlignment.Center,
                BackgroundStyleBoxOverride = new StyleBoxFlat(Color.FromHex("#2a2a30")),
                ForegroundStyleBoxOverride = _progressFill,
            };
            _stored = new Label { MinWidth = 110, Align = Label.AlignMode.Right };
            progressLine.AddChild(_progress);
            progressLine.AddChild(_stored);
            lines.AddChild(progressLine);

            var buttons = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 4 };
            var orders = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 4 };
            _toggle = new Button { HorizontalExpand = true, ClipText = true, StyleClasses = { StyleBase.ButtonSquare } };
            _toggle.OnPressed += _ => OnToggle?.Invoke(_machine);
            _dispense = new Button
            {
                HorizontalExpand = true,
                ClipText = true,
                Text = Loc.GetString("persistent-poi-production-ui-dispense"),
                StyleClasses = { StyleBase.ButtonSquare },
            };
            _dispense.OnPressed += _ => OnDispense?.Invoke(_machine);
            _decommission = new Button
            {
                HorizontalExpand = true,
                ClipText = true,
                Text = Loc.GetString("persistent-poi-production-ui-decommission"),
                StyleClasses = { StyleBase.ButtonCaution },
            };
            _decommission.OnPressed += _ => OnDecommissionPressed();
            _rush = new Button { HorizontalExpand = true, ClipText = true, StyleClasses = { StyleBase.ButtonSquare } };
            _rush.OnPressed += _ => OnRush?.Invoke(_machine);
            buttons.AddChild(_toggle);
            buttons.AddChild(_dispense);
            orders.AddChild(_rush);
            orders.AddChild(_decommission);
            lines.AddChild(buttons);
            lines.AddChild(orders);
        }

        public void Update(PersistentPoiProductionMachineState state)
        {
            _updating = true;

            _name.SetTextIfChanged(state.Name);
            _status.SetTextIfChanged(Loc.GetString(state.Status.GetLocId(),
                ("percent", (int) MathF.Round(state.Power * 100f))));
            _status.FontColorOverride = StatusColor(state.Status);

            if (!_recipeIds.SequenceEqual(state.RecipeIds))
            {
                _recipes.Clear();
                for (var i = 0; i < state.RecipeIds.Count; i++)
                {
                    _recipes.AddItem(state.RecipeNames[i], i);
                }

                _recipeIds = new List<string>(state.RecipeIds);
            }

            var selected = state.SelectedRecipe == null ? -1 : _recipeIds.IndexOf(state.SelectedRecipe);
            if (selected >= 0 && _recipes.SelectedId != selected)
                _recipes.SelectId(selected);

            var heldBack = _remote && state.Stored > 0;
            _recipes.Disabled = _locked || _recipeIds.Count <= 1 || heldBack;
            _recipes.ToolTip = heldBack ? Loc.GetString("persistent-poi-production-ui-remote-recipe-locked") : null;

            _output.SetTextIfChanged(state.Output.Length == 0
                ? string.Empty
                : Loc.GetString("persistent-poi-production-ui-output", ("output", state.Output)));

            _progress.Value = state.Progress;
            _progressFill.BackgroundColor = state.Status switch
            {
                PersistentPoiProductionStatus.Running => ConsolePalette.Good,
                PersistentPoiProductionStatus.LowPower => ConsolePalette.Warn,
                _ => ConsolePalette.Muted,
            };

            _stored.SetTextIfChanged(Loc.GetString("persistent-poi-production-ui-stored",
                ("stored", state.Stored),
                ("max", state.MaxStored)));
            _stored.FontColorOverride = state.Stored >= state.MaxStored ? ConsolePalette.Warn : ConsolePalette.Normal;

            _toggle.Text = Loc.GetString(state.Enabled
                ? "persistent-poi-production-ui-turn-off"
                : "persistent-poi-production-ui-turn-on");
            _dispense.Disabled = state.Stored <= 0;

            _updating = false;
        }

        public void SetRush(int price, bool affordable)
        {
            _rush.Text = price > 0
                ? Loc.GetString("persistent-poi-rush-button", ("price", price))
                : Loc.GetString("persistent-poi-rush-button-idle");
            _rush.Disabled = price <= 0 || !affordable;
            _rush.ToolTip = Loc.GetString("persistent-poi-rush-tooltip");
        }

        public void SetRemote(bool remote)
        {
            _remote = remote;
            _dispense.Visible = !remote;
            _decommission.Visible = !remote;
        }

        public void SetLocked(bool locked)
        {
            _locked = locked;
            _toggle.Disabled = locked;
            _recipes.Disabled = locked || _recipeIds.Count <= 1;
        }

        private void OnRecipePicked(OptionButton.ItemSelectedEventArgs args)
        {
            if (_updating || args.Id < 0 || args.Id >= _recipeIds.Count)
                return;

            _recipes.SelectId(args.Id);
            OnSelectRecipe?.Invoke(_machine, _recipeIds[args.Id]);
        }

        private void OnDecommissionPressed()
        {
            if (!_decommissionArmed)
            {
                _decommissionArmed = true;
                _decommission.Text = Loc.GetString("persistent-poi-production-ui-decommission-confirm");
                return;
            }

            _decommissionArmed = false;
            _decommission.Text = Loc.GetString("persistent-poi-production-ui-decommission");
            OnDecommission?.Invoke(_machine);
        }

        private static Color StatusColor(PersistentPoiProductionStatus status)
        {
            return status switch
            {
                PersistentPoiProductionStatus.Running => ConsolePalette.Good,
                PersistentPoiProductionStatus.Full => ConsolePalette.Warn,
                PersistentPoiProductionStatus.Starting => ConsolePalette.Warn,
                PersistentPoiProductionStatus.LowPower => ConsolePalette.Warn,
                PersistentPoiProductionStatus.Disabled => ConsolePalette.Muted,
                _ => ConsolePalette.Bad,
            };
        }
    }
}
