using Content.Client.Message;
using Content.Client.UserInterface.Controls;
using Content.Shared._Crescent.Territory;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client._Crescent.Territory;

[GenerateTypedNameReferences]
public sealed partial class PersistentPoiMappingWindow : FancyWindow
{
    [Dependency] private readonly IEntityManager _entMan = default!;

    private const float RefreshInterval = 0.5f;

    private readonly PersistentPoiBuildSystem _build;
    private float _sinceRefresh = RefreshInterval;

    public event Action? OnMenu;
    public event Action? OnDismantle;
    public event Action? OnPaint;
    public event Action? OnRecenter;
    public event Action? OnLeave;

    public PersistentPoiMappingWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _build = _entMan.System<PersistentPoiBuildSystem>();

        HintLabel.SetMarkup(Loc.GetString("persistent-poi-mapping-ui-hint"));
        MenuButton.OnPressed += _ => OnMenu?.Invoke();
        DismantleButton.OnPressed += _ => OnDismantle?.Invoke();
        PaintButton.OnPressed += _ => OnPaint?.Invoke();
        RecenterButton.OnPressed += _ => OnRecenter?.Invoke();
        LeaveButton.OnPressed += _ => OnLeave?.Invoke();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        DismantleButton.Pressed = _build.IsDeconstructing;

        _sinceRefresh += args.DeltaSeconds;
        if (_sinceRefresh < RefreshInterval)
            return;

        _sinceRefresh = 0f;

        TerritoryLabel.Text = _build.TryGetTerritory(out var territory)
            ? _entMan.GetComponent<MetaDataComponent>(territory).EntityName
            : Loc.GetString("persistent-poi-build-ui-no-territory");

        SiloLabel.SetMarkup(_build.TryGetSiloStock(out var kinds, out var total)
            ? Loc.GetString("persistent-poi-mapping-ui-silo", ("kinds", kinds), ("total", total))
            : Loc.GetString("persistent-poi-mapping-ui-no-silo"));
    }
}
