using System.Linq;
using Content.Client._Crescent.UI;
using Content.Shared._Crescent.Factions;
using Content.Shared._Crescent.Territory;
using Content.Shared.CaptureFlag;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Crescent.Territory;

[GenerateTypedNameReferences]
public sealed partial class TerritoryConsolePanel : BoxContainer
{
    public event Action<string>? OnSelect;

    private readonly Dictionary<string, TerritoryRow> _rows = new(StringComparer.OrdinalIgnoreCase);

    public TerritoryConsolePanel()
    {
        RobustXamlLoader.Load(this);
        EmptyListLabel.SetHint(Loc.GetString("territory-console-list-empty"));

        Administration.Remote = true;
        Production.Remote = true;

        TabContainer.SetTabTitle(Administration, Loc.GetString("territory-console-tab-development"));
        TabContainer.SetTabTitle(Production, Loc.GetString("territory-console-tab-production"));
        TabContainer.SetTabTitle(Command, Loc.GetString("territory-console-tab-command"));
    }

    public void UpdateState(TerritoryConsoleState state)
    {
        UpdateList(state);
        UpdateDetails(state);
    }

    private void UpdateList(TerritoryConsoleState state)
    {
        FactionNote.Visible = !state.CanHoldTerritory;
        FactionNote.SetHint(Loc.GetString("territory-console-faction-cannot-hold"));
        EmptyListLabel.Visible = state.Territories.Count == 0;

        var seen = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        for (var i = 0; i < state.Territories.Count; i++)
        {
            var territory = state.Territories[i];
            seen.Add(territory.RegionId);

            if (!_rows.TryGetValue(territory.RegionId, out var row))
            {
                row = new TerritoryRow(territory.RegionId);
                row.OnPressed += id => OnSelect?.Invoke(id);
                _rows[territory.RegionId] = row;
                TerritoryList.AddChild(row);
            }

            row.Update(territory, state.Faction, string.Equals(territory.RegionId, state.Selected, StringComparison.OrdinalIgnoreCase));
            row.SetPositionInParent(i);
        }

        foreach (var (id, row) in _rows.ToArray())
        {
            if (seen.Contains(id))
                continue;

            TerritoryList.RemoveChild(row);
            _rows.Remove(id);
        }
    }

    private void UpdateDetails(TerritoryConsoleState state)
    {
        var selected = state.Territories.FirstOrDefault(t =>
            string.Equals(t.RegionId, state.Selected, StringComparison.OrdinalIgnoreCase));

        var held = state.Administration != null && state.Production != null;

        var commandOnly = !held && state.SelectedHeld;
        DetailsRow.Visible = held || commandOnly;
        LinksRow.Visible = held;
        DetailsNote.Visible = !held && !commandOnly;
        TabContainer.SetTabVisible(Administration, held);
        TabContainer.SetTabVisible(Production, held);
        if (commandOnly)
            DetailsRow.CurrentTab = Command.GetPositionInParent();

        if (state.SelectedHeld)
            Command.UpdateState(state);

        if (selected == null)
        {
            SelectedHeading.SetTextIfChanged(Loc.GetString("territory-console-nothing-selected"));
            SelectedStatus.SetTextIfChanged(string.Empty);
            DetailsNote.SetHint(Loc.GetString("territory-console-pick-hint"));
            return;
        }

        SelectedHeading.SetTextIfChanged(selected.Name);
        SelectedStatus.SetTextIfChanged(DescribeStatus(selected, state.Faction, out var color));
        SelectedStatus.FontColorOverride = color;

        if (!held)
        {
            DetailsNote.SetHint(Loc.GetString(!selected.Loaded
                ? "territory-console-not-loaded-details"
                : "territory-console-not-held-details"));
            return;
        }

        ProductionLink.SetTextIfChanged(Loc.GetString(state.ProductionLinked
            ? "territory-console-production-linked"
            : "territory-console-production-unlinked"));
        ProductionLink.FontColorOverride = state.ProductionLinked ? ConsolePalette.Good : ConsolePalette.Bad;

        Production.Locked = !state.ProductionLinked;
        Administration.UpdateState(state.Administration!);
        Production.UpdateState(state.Production!);
    }

    private static string DescribeStatus(TerritorySummary territory, string? faction, out Color color)
    {
        if (!territory.Loaded)
        {
            color = ConsolePalette.Muted;
            return Loc.GetString("territory-console-status-not-loaded",
                ("holder", HolderName(territory.Owner)));
        }

        var ours = territory.Owner != null && territory.Owner == faction;
        if (!ours)
        {
            color = territory.Owner == null ? ConsolePalette.Muted : ConsolePalette.Normal;
            return Loc.GetString("territory-console-status-other", ("holder", HolderName(territory.Owner)));
        }

        if (territory.Stage != CaptureFlagStage.Idle)
        {
            color = ConsolePalette.Bad;
            return Loc.GetString(territory.Stage == CaptureFlagStage.Contested
                    ? "territory-console-status-contested"
                    : "territory-console-status-under-attack",
                ("attacker", HolderName(territory.Attacker)),
                ("percent", (int) MathF.Round(territory.Progress * 100f)));
        }

        color = ConsolePalette.Good;
        return Loc.GetString("territory-console-status-held",
            ("running", territory.WorksRunning),
            ("works", territory.Works),
            ("stored", territory.Stored));
    }

    private static string HolderName(string? faction)
    {
        return faction == null
            ? Loc.GetString("territory-console-unclaimed")
            : FactionDisplay.Abbreviation(faction);
    }

    private sealed class TerritoryRow : BoxContainer
    {
        public event Action<string>? OnPressed;

        private readonly string _regionId;
        private readonly Button _button;
        private readonly Label _status;

        public TerritoryRow(string regionId)
        {
            _regionId = regionId;
            Orientation = LayoutOrientation.Vertical;

            _button = new Button { ToggleMode = true, HorizontalExpand = true, ClipText = true };
            _button.OnPressed += _ => OnPressed?.Invoke(_regionId);
            _status = new Label { ClipText = true, Margin = new Thickness(6, 0, 0, 0) };

            AddChild(_button);
            AddChild(_status);
        }

        public void Update(TerritorySummary territory, string? faction, bool selected)
        {
            var text = Loc.GetString("territory-console-row",
                ("name", territory.Name),
                ("level", territory.Level));
            if (_button.Text != text)
                _button.Text = text;

            _button.Pressed = selected;
            _status.SetTextIfChanged(DescribeStatus(territory, faction, out var color));
            _status.FontColorOverride = color;
        }
    }
}
