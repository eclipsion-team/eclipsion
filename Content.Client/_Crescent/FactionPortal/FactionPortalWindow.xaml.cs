using Content.Client.UserInterface.Controls;
using Content.Shared._Crescent.FactionPortal;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Crescent.FactionPortal;

[GenerateTypedNameReferences]
public sealed partial class FactionPortalWindow : FancyWindow
{
    public event Action<NetEntity>? OnDestinationPicked;

    public FactionPortalWindow()
    {
        RobustXamlLoader.Load(this);
    }

    public void UpdateState(FactionPortalBuiState state)
    {
        DestinationList.RemoveAllChildren();

        if (!state.Open)
        {
            StatusLabel.Text = Loc.GetString("faction-portal-ui-closed");
            return;
        }

        if (state.Destinations.Count == 0)
        {
            StatusLabel.Text = Loc.GetString("faction-portal-ui-no-destinations");
            return;
        }

        StatusLabel.Text = Loc.GetString("faction-portal-ui-hint");

        foreach (var destination in state.Destinations)
        {
            var button = new Button
            {
                Text = destination.Name,
                HorizontalExpand = true,
                ClipText = true,
                Margin = new Thickness(0, 0, 0, 4),
            };

            var target = destination.Portal;
            button.OnPressed += _ => OnDestinationPicked?.Invoke(target);
            DestinationList.AddChild(button);
        }
    }
}
