using System.Numerics;
using Content.Shared.Localizations;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Crescent.Translator;

[GenerateTypedNameReferences]
public sealed partial class LanguagePickerWindow : DefaultWindow
{
    public event Action<string>? Picked;

    public LanguagePickerWindow()
    {
        RobustXamlLoader.Load(this);

        foreach (var name in ContentLocalizationManager.Languages)
        {
            var button = new Button
            {
                Text = Loc.GetString($"language-name-{name}"),
                MinSize = new Vector2(120, 40),
            };
            button.OnPressed += _ => Picked?.Invoke(name);
            Buttons.AddChild(button);
        }
    }
}
