using Content.Shared.CCVar;
using Content.Shared.Localizations;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Configuration;

namespace Content.Client._Crescent.Translator;

[GenerateTypedNameReferences]
public sealed partial class LanguageOptions : BoxContainer
{
    [Dependency] private readonly IConfigurationManager _cfg = default!;
    [Dependency] private readonly ILocalizationManager _loc = default!;
    [Dependency] private readonly IUserInterfaceManager _ui = default!;

    public LanguageOptions()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        var languages = ContentLocalizationManager.Languages;
        for (var i = 0; i < languages.Length; i++)
        {
            LanguageOption.AddItem(Loc.GetString($"language-name-{languages[i]}"), i);
            if (languages[i] == _loc.DefaultCulture?.Name)
                LanguageOption.SelectId(i);
        }

        LanguageOption.OnItemSelected += args =>
        {
            LanguageOption.SelectId(args.Id);
            _ui.GetUIController<LanguageUIController>().Pick(languages[args.Id]);
        };

        AutoTranslateCheckBox.Pressed = _cfg.GetCVar(CCVars.TranslatorAuto);
        AutoTranslateCheckBox.Disabled = !_cfg.GetCVar(CCVars.TranslatorEnabled);
        AutoTranslateCheckBox.OnToggled += args =>
        {
            _cfg.SetCVar(CCVars.TranslatorAuto, args.Pressed);
            _cfg.SaveToFile();
        };
    }
}
